-- State-only redraw: no source rescan, so a click does not trigger a guild
-- roster pass. Under Favourites or Hidden the changed row has just left the
-- list it is sitting in, so those two re-filter instead. Scroll position is
-- kept.
function RM.SoftRefresh()
  if not RM._frame then return end

  CountCategories()
  if STATEFUL_FILTERS[RM._filter or "all"] then
    ApplyFilter()
    UpdateCategoryBar()
    RelayoutList(false)
    return
  end

  UpdateCategoryBar()
  UpdateSummary()
  UpdateVisibleRows()
end

-- Collects again from every source, measures, sorts, filters and draws. The
-- options call it when a source is switched on or off.
function RM.Refresh(resetScroll)
  local frame = RM._frame
  if not frame then return end
  RM._entries = Collect()
  -- A category whose source was switched off has no tile to stand under.
  local category = ActiveCategory()
  if category.source and COLLECT.off[category.source] then RM._filter = "all" end
  RM.Measure(frame)
  CountCategories()
  SortEntries()
  ApplyFilter()
  UpdateCategoryBar()
  RelayoutList(resetScroll)
end

-- One name's favourite, from its row.
function RM.ToggleFavorite(entry)
  local R = Recipients()
  if not entry or not R then return end
  local on = not entry.fav
  R.SetFavorite(entry.key, on)
  entry.fav = on
  -- SetFavorite clears hidden by design; mirror it so the row does not have to
  -- wait for a rescan to stop looking hidden.
  if on and entry.hidden then
    entry.hidden = false
    entry._nameGen = nil
  end
  entry.stale = StaleFor(entry)
  ToggleSound(on)
  RM.SoftRefresh()
end

-- One name hidden, or shown again. Hiding takes the star away
-- (Recipients.SetHidden clears it).
function RM.ToggleHidden(entry)
  local R = Recipients()
  if not entry or not R then return end
  local on = not entry.hidden
  R.SetHidden(entry.key, on)
  entry.hidden = on
  if on then entry.fav = false end
  entry._nameGen = nil
  entry.stale = StaleFor(entry)
  ToggleSound(on)
  RM.SoftRefresh()
end

-- Switches the active category. Scroll resets: the list underneath is a
-- different set of names.
function RM.SetFilter(id)
  local category = CATEGORY_BY_ID[id or "all"]
  if not category then return end
  if RM._filter == category.id then return end
  RM._filter = category.id
  if not RM._frame then return end
  ApplyFilter()
  UpdateCategoryBar()
  RelayoutList(true)
end

-- What the search box holds now.
function RM.SetQuery(text)
  RM._query = text or ""
  RM._queryLower = Lower(Trim(RM._query))
  if not RM._frame then return end
  ApplyFilter()
  RelayoutList(true)
end

-- The order changed: the sort button and its menu told, the list sorted and
-- shown from its top.
function RM.SortChanged()
  if not RM._frame then return end
  if RM._frame.RefreshSortControl then RM._frame.RefreshSortControl() end
  SortEntries()
  ApplyFilter()
  RelayoutList(true)
end

-- Sets the sort field, or reverses the direction when the field is already
-- selected and `toggleDirection` asks it. Picking a new field starts it in
-- its own most-useful direction.
function RM.SetSort(id, toggleDirection)
  local sort = SORT_BY_ID[id or "name"]
  if not sort then return end

  if RM._sort == sort.id and toggleDirection then
    RM._sortDesc = not RM._sortDesc
  elseif RM._sort ~= sort.id then
    RM._sort = sort.id
    RM._sortDesc = sort.desc and true or false
  else
    return
  end
  RM.SortChanged()
end

-- The field in force, in this direction: descending (`desc`) or ascending.
function RM.SetSortDirection(desc)
  desc = desc and true or false
  if (RM._sortDesc and true or false) == desc then return end
  RM._sortDesc = desc
  RM.SortChanged()
end

-- The order a first open shows: Name, A to Z.
function RM.SortIsDefault()
  return (RM._sort or "name") == "name" and not RM._sortDesc
end

-- The sort button's right-click and its menu's Reset: Name, A to Z.
function RM.ResetSort()
  if RM.SortIsDefault() then return end
  RM._sort, RM._sortDesc = "name", false
  RM.SortChanged()
end

function RM.AddRecipient(text)
  local R = Recipients()
  if not R then
    Notice(L["RM_ERR_NOT_READY"])
    return
  end
  local key, err = R.AddManual(text)
  if not key then
    -- AddManual reports a locale KEY, not a sentence.
    Notice(L[err or "RM_ERR_NOT_READY"])
    return
  end
  -- Clear whatever is narrowing the list so the freshly added name is actually
  -- on screen.
  if RM._frame and RM._frame.SearchBox then RM._frame.SearchBox:SetText("") end
  RM._query, RM._queryLower = "", ""
  RM._filter = "all"
  RM.Refresh(true)
