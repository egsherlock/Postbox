-- =====================================================================
-- Postbox :: recipient manager window
-- ---------------------------------------------------------------------
-- Curation UI on top of Core/Recipients.lua. Postbox offers a recipient
-- for every character the game hands it -- guild, friends, recent allies,
-- Blizzard's account autocomplete, plus its own saved alts and mail
-- history. On an account with a decade of alts that list is mostly noise,
-- and this window is where it gets trimmed.
--
-- Two things shape the whole file:
--
-- 1. The state map is SPARSE (see Recipients.lua): only recipients with
--    non-default state have a stored row. So the list is the UNION of the
--    live sources and the stored rows, never just the stored table.
--
-- 2. The list can be several hundred rows on a big guild. Rows are pooled
--    AND virtualised: only the ~15 rows that fit the viewport are ever
--    created, and scrolling re-fills them. WoW cannot free a frame, so a
--    "one frame per recipient" list is a permanent cost paid by everyone
--    with a large guild.
--
-- Deleting is deliberately not offered for everything. A guild member or
-- autocomplete hit is regenerated by the next scan, so "delete" would be a
-- lie; Recipients.CanDelete says which is which and the button explains
-- itself when disabled.
-- =====================================================================

