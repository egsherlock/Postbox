-- Row pool
--
-- Only the rows that fit the viewport exist. Scrolling re-fills them, so the
-- pool never grows past what one screenful needs no matter how many recipients
-- the account has.
-------------------------------------------------------------
-- ONE meaning for right-click-on-a-name, across both windows.
--
-- Right-click favourited in the Send tab's picker and edited a note here, both
-- advertised in their own tooltip -- the same object, the same gesture, two
-- unrelated outcomes, and the single most confusing thing in the feature. It is
-- the frequent action and it is already taught on every picker row, so it wins;
-- notes move to the row's own button, which is where an occasional action with
-- a dialog behind it belongs anyway.
local function ToggleFavorite(entry)
  local R = Recipients()
  if not entry or not R then return end
  local on = not entry.fav
  R.SetFavorite(entry.key, on)
  entry.fav = on
  -- SetFavorite clears hidden by design; mirror it so the row does not have to
  -- wait for a rescan to stop looking hidden.
  if on then entry.hidden = false end
  entry.stale = StaleFor(entry)
  ToggleSound(on)
  RM.SoftRefresh()
end

local function BuildRow(parent)
  local row = CreateFrame("Button", nil, parent)
  row:SetHeight(ROW_H)
  row:RegisterForClicks("RightButtonUp")

  -- The stripe texture is Theme.StyleMailRow's to create and to paint; FillRow
  -- calls it with the row's DISPLAYED position, so this list stripes with the
  -- same warm primitive the mail list and the contact picker use instead of a
  -- flat white wash of its own.
  local highlight = row:CreateTexture(nil, "HIGHLIGHT")
  highlight:SetAllPoints()
  Theme.FillColor(highlight, "stripeHover")

  -- Favourite. Icon-only, so deliberately NOT tagged __postboxButton: the skins
  -- only restyle the addon's push-buttons.
  --
  -- The hit area is larger than the star so the click target is comfortable
  -- without the artwork having to fill it; the star itself is centred at a size
  -- that reads without leaning in.
  row.Fav = CreateFrame("Button", nil, row)
  row.Fav:SetSize(22, 22)
  row.Fav:SetPoint("LEFT", row, "LEFT", 5, 0)
  row.Fav.Icon = row.Fav:CreateTexture(nil, "ARTWORK")
  row.Fav.Icon:SetSize(17, 17)
  row.Fav.Icon:SetPoint("CENTER")
  SetStarArt(row.Fav.Icon, false)
  local favHi = row.Fav:CreateTexture(nil, "HIGHLIGHT")
  favHi:SetAllPoints()
  Theme.FillColor(favHi, "plateHighlight")

  -- Measured, never fixed. This was 64px hard-coded around a caption that comes
  -- out of a locale file, and the German and Russian words for "Delete" are both
  -- wider than the English one -- so it clipped. Constant width plus word wrap
  -- off is exactly the pairing the design system bans.
  row.Delete = Theme.CreateButton(nil, row)
  row.Delete:SetPoint("RIGHT", row, "RIGHT", -6, 0)
  row.Delete:SetText(L["RM_BTN_DELETE"])
  Theme.SizeToText(row.Delete, { minWidth = ROW_BTN_MIN_W, maxWidth = ROW_BTN_MAX_W,
                                 height = ROW_BTN_H })
  -- Without this a disabled button stops firing OnEnter, and the tooltip that
  -- explains WHY it is disabled would never appear.
  if row.Delete.SetMotionScriptsWhileDisabled then
    row.Delete:SetMotionScriptsWhileDisabled(true)
  end

  row.HideLabel = Theme.CreateText(row, "label")
  row.HideLabel:SetPoint("RIGHT", row.Delete, "LEFT", -8, 0)
  row.HideLabel:SetText(L["RM_COL_HIDE"])

  row.HideCheck = CreateFrame("CheckButton", nil, row, "UICheckButtonTemplate")
  row.HideCheck:SetSize(22, 22)
  row.HideCheck:SetPoint("RIGHT", row.HideLabel, "LEFT", -2, 0)
  -- Both tags are required: the skins find the box by __postboxCheck and its
  -- caption by __label.
  row.HideCheck.__postboxCheck = true
  row.HideCheck.__label = row.HideLabel

  -- Notes get an explicit control rather than a hidden gesture. It is a word
  -- and not a glyph for the same reason every other control in this window is:
  -- an unlabelled icon has to be discovered, and this one would be discovered
  -- by right-clicking, which now means something else.
  row.Note = Theme.CreateButton(nil, row)
  row.Note:SetPoint("RIGHT", row.HideCheck, "LEFT", -8, 0)
  row.Note:SetText(L["RM_BTN_NOTE"])
  Theme.SizeToText(row.Note, { minWidth = ROW_BTN_MIN_W, maxWidth = ROW_BTN_MAX_W,
                               height = ROW_BTN_H })

  -- A container so the two text lines can share one right edge without either
  -- of them anchoring across the controls.
  row.TextArea = CreateFrame("Frame", nil, row)
  row.TextArea:SetPoint("TOPLEFT", row, "TOPLEFT", 31, -2)
  row.TextArea:SetPoint("BOTTOM", row, "BOTTOM", 0, 2)
  row.TextArea:SetPoint("RIGHT", row.Note, "LEFT", -8, 0)

  row.Name = Theme.CreateText(row.TextArea, "bodySmall")
  row.Name:SetPoint("TOPLEFT", row.TextArea, "TOPLEFT", 0, 0)
  row.Name:SetPoint("RIGHT", row.TextArea, "RIGHT", 0, 0)
  row.Name:SetJustifyH("LEFT")
  row.Name:SetWordWrap(false)

  -- `secondary`, never the disabled font object: this line carries the
  -- category, the class, the level, the last-played time and the note. It is
  -- the densest line on the row and it is not inactive.
  row.Meta = Theme.CreateText(row.TextArea, "secondary")
  row.Meta:SetPoint("BOTTOMLEFT", row.TextArea, "BOTTOMLEFT", 0, 1)
  row.Meta:SetPoint("RIGHT", row.TextArea, "RIGHT", 0, 0)
  row.Meta:SetJustifyH("LEFT")
  row.Meta:SetWordWrap(false)

  -- Handlers are installed once and read row._entry, so a recycled row never
  -- acts on the recipient it used to show.
  row.Fav:SetScript("OnClick", function()
    ToggleFavorite(row._entry)
  end)
  row.Fav:SetScript("OnEnter", function(self)
    local entry = row._entry
    GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
    GameTooltip:SetText(L["CONTACT_FAVORITES"])
    GameTooltip:AddLine(entry and entry.fav and L["RM_TIP_FAV_ON"] or L["RM_TIP_FAV_OFF"],
                        1, 1, 1, true)
    GameTooltip:Show()
  end)
  row.Fav:SetScript("OnLeave", function() GameTooltip:Hide() end)

  row.HideCheck:SetScript("OnClick", function(self)
    local entry = row._entry
    local R = Recipients()
    if not entry or not R then
      if self.SetChecked then self:SetChecked(false) end
      return
    end
    local on = self:GetChecked() and true or false
    R.SetHidden(entry.key, on)
    entry.hidden = on
    -- SetHidden clears fav by design; mirror it rather than letting the row
    -- keep a star it no longer has.
    if on then entry.fav = false end
    entry.stale = StaleFor(entry)
    ToggleSound(on)
    RM.SoftRefresh()
  end)
  row.HideCheck:SetScript("OnEnter", function(self)
    GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
    GameTooltip:SetText(L["RM_COL_HIDE"])
    GameTooltip:AddLine(L["RM_TIP_HIDE"], 1, 1, 1, true)
    GameTooltip:Show()
  end)
  row.HideCheck:SetScript("OnLeave", function() GameTooltip:Hide() end)

  row.Delete:SetScript("OnClick", function()
    local entry = row._entry
    if entry then RM.ConfirmDelete(entry.key, entry.display) end
  end)
  row.Delete:SetScript("OnEnter", function(self)
    local entry = row._entry
    GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
    GameTooltip:SetText(L["RM_BTN_DELETE"])
