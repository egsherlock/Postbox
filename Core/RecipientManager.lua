  if not shown.played then Theme.TipFact(L["RM_FACT_PLAYED"], entry.playedText) end
  if not shown.mailed then Theme.TipFact(L["RM_FACT_MAILED"], entry.mailedText) end
  Theme.TipFact(L["RM_FACT_GROUPS"], GroupsOf(entry))
  if entry.note then
    Theme.TipFact(L["RM_FACT_NOTE"], Theme.TipTone("muted", "\"" .. entry.note .. "\""))
  end
  -- One of the player's own characters with nothing recorded yet: the row's
  -- Level and Played are blank, and this says when they fill in.
  if not entry.level and not entry.lastSeen and TracksActivity(entry) then
    local muted = Theme.TIP_MUTED
    GameTooltip:AddLine(L["RM_TIP_ALT_UNRECORDED"], muted, muted, muted, true)
  end
  if entry.stale then Theme.TipLine(Theme.TipTone("warning", L["RM_TIP_STALE"])) end
  Theme.TipHint(entry.hidden and L["RM_HINT_ROW_HIDDEN"] or L["RM_HINT_ROW"])
  GameTooltip:Show()
end

-- A mark's tooltip: what it is, what it does, and its click.
function RM.MarkTip(mark)
  local row = mark._row
  local entry = row and row._entry
  if not entry then return end
  Theme.TipBegin(mark, "ANCHOR_RIGHT")
  if mark == row.NoteMark then
    Theme.TipTitle(L["RM_BTN_NOTE"])
    Theme.TipLine(L["RM_TIP_NOTE"])
    if entry.note then
      Theme.TipFact(L["RM_FACT_NOTE"], Theme.TipTone("muted", "\"" .. entry.note .. "\""))
    end
    Theme.TipHint(entry.note and L["RM_HINT_NOTE_EDIT"] or L["RM_HINT_NOTE_ADD"])
  elseif mark == row.EyeMark then
    if entry.hidden then
      Theme.TipTitle(L["RM_FILTER_HIDDEN"])
      Theme.TipLine(L["RM_TIP_SHOW"])
      Theme.TipHint(L["RM_HINT_SHOW"])
    else
      Theme.TipTitle(L["RM_COL_HIDE"])
      Theme.TipLine(L["RM_TIP_HIDE"])
      Theme.TipHint(L["RM_HINT_HIDE"])
    end
  else
    Theme.TipTitle(L["RM_BTN_DELETE"])
    if entry.canDelete then
      Theme.TipLine(L["RM_TIP_DELETE"])
      Theme.TipHint(L["RM_HINT_DELETE"])
    else
      Theme.TipLine(Theme.TipTone("warning", L[entry.deleteReason or "RM_ERR_LIVE_ONLY"]))
    end
  end
  GameTooltip:Show()
end

