-- Category tile / direction button plating
--
-- Theme.CreatePlate, and nothing of this window's own.
--
-- This was the THIRD hand-rolled plate in the addon and the one furthest
-- outside the design system. It painted `_bg:SetColorTexture(1, 1, 1, fill)` at
-- 0.10 / 0.17 / 0.26 -- the same defect the Send tab's bar was reported for:
-- white at a tenth to a quarter of an alpha is 74% to 90% see-through, so under
-- a host UI whose window follows the user's own opacity the game world rendered
-- through the filter bar. It also carried three text colours of its own and a
-- fourth gold ({1.00, 0.82, 0.30}) that was neither the brand accent nor the
-- host UI's, so a window that is supposed to read as part of Postbox had its
-- own palette.
--
-- All of that is the factory's now: a ladder that rises in colour AND alpha
-- together (0.94 idle to 0.99 selected, so the more prominent state is always
-- the more substantial one), one ring, one bevel, one hover wash, and captions
-- in the accent tones derived from whichever accent is live.
--
-- The category tiles take the `segment` variant, which carries the selected
-- underline. That is the one place this bar deliberately differs from the Send
-- tab's, which takes `tile`: there "active" means "this list is open right now"
-- and lasts a moment, whereas here it is persistent state the whole window is
-- filtered by, and fill plus caption tone alone is not emphatic enough to
-- explain why a 316-name list is showing twelve rows.
-------------------------------------------------------------

-- The factory owns fill, ring, bevel, hover wash and caption tone. The one fact
-- it cannot know is that a category is EMPTY -- a property of the data, not of
-- the control -- so that caption is re-tinted after every repaint the factory
-- makes, including the hover repaints it installs itself.
local function TintEmptyCaption(tile)
  if tile and tile.Text and tile._empty and not tile._active then
    -- Nothing in this category. Still clickable: the empty state it lands on
    -- explains the category better than a disabled button would.
    Theme.SetColor(tile.Text, "textDisabled")
  end
end

local function StyleTile(tile)
  if not tile then return end

  -- The star tile with favourites behind it is `flagged`: one step up from
  -- idle and no more. Active still wins -- "this is the filter the list is
  -- under" is the more urgent fact, and the gold count beside the star says
  -- the rest.
  Theme.SetPlateFlagged(tile, tile._starTile and not tile._empty)
  -- Last, and the only call here that paints: SetPlateSelected honours a
  -- host-UI skin's __setSelectedOverride, after which the skin owns the whole
  -- visual and our plate art is retired for good.
  Theme.SetPlateSelected(tile, tile._active and true or false)
  TintEmptyCaption(tile)
end

-- Count text for the Favourites tile. nil means "show no number", which is the
-- empty state: a bare "0" would be one more thing to read where the hollow star
-- has already said it.
local function TileCountText(count)
  if not count or count <= 0 then return nil end
  if count > BAR_COUNT_CAP then return BAR_COUNT_CAP .. "+" end
  return tostring(count)
end

-- Sizes the star tile around its count. The width is derived from the rendered
-- string, so the bar's own layout pass has to run again afterwards -- see
-- UpdateCategoryBar.
local function SetTileCount(tile, count)
  if not tile or not tile.Count then return end
  local text = TileCountText(count)
  if text then
    tile.Count:SetText(text)
    tile.Count:Show()
    tile:SetWidth(BAR_STAR_W + BAR_COUNT_GAP + math.ceil(tile.Count:GetStringWidth() or 0))
  else
    tile.Count:Hide()
    tile:SetWidth(BAR_STAR_W)
  end
end

-- The plate itself, shared by the category tiles and the sort direction button.
-- Deliberately not tagged __postboxButton -- the host-UI skins restyle the
-- addon's push buttons, and these are flat plates that would come back as
-- full-size buttons. Theme.CreatePlate does not tag them either; the art it
-- creates goes into `__pbPlateArt`, which is what a skin retires instead.
--
-- `variant` is a Theme.PlateVariants key: "segment" for the category tiles,
-- which carry the selected underline, "tile" for the sort direction button,
-- which has no selected state to underline.
--
-- HookScript, never SetScript: the factory installs the hover repaint on
-- OnEnter/OnLeave, and replacing those is how a plate silently stops repainting
-- on hover. The hooks run after it, which is what the empty-caption re-tint
-- needs.
local function CreateTile(parent, variant)
  local tile = Theme.CreatePlate(parent, variant)

  tile:HookScript("OnEnter", function(self)
    TintEmptyCaption(self)
    if self._onEnter then self._onEnter(self) end
  end)
  tile:HookScript("OnLeave", function(self)
    TintEmptyCaption(self)
    GameTooltip:Hide()
  end)

  StyleTile(tile)
  return tile
end

-------------------------------------------------------------
-- Data collection
--
-- Returns entries, total, hiddenCount, favouriteCount.
--
-- Every entry is:
--   key, display, search, sortName, category, rank, cats,
--   live, hidden, fav, manual, note, level, lastSeen, faction, stale
-------------------------------------------------------------
local function Collect()
  local R = Recipients()
  local entries, byKey = {}, {}
  if not R then return entries, 0, 0, 0 end

  local CS = ns.ContactService

  local buckets
  if CS and type(CS.BuildSuggestions) == "function" then
    -- includeHidden, and this is the ONE caller that passes it for browsing.
    --
    -- This window is the curation UI: it is where a hidden recipient is found
    -- and brought back. Without this the live sources arrived pre-filtered, so
    -- every hidden name reached the list only through the stored-state overlay
    -- below, with no source and no category -- and the window then relabelled
    -- your hidden guildmate "Saved", refused to find them under the Guild
    -- filter, and printed "Not in any current list" on the row the moment you
    -- unticked Hide. All four of those were the same missing argument.
    local ok, result = pcall(CS.BuildSuggestions, "", { includeHidden = true })
    if ok and type(result) == "table" then buckets = result end
  end
  buckets = buckets or {}

  -- STALE DETECTION SAFETY GATE.
  --
  -- The guild roster and the friends list load asynchronously and return an
  -- empty list on a cold call. Marking "not returned this pass" as stale would
  -- flag the user's entire guild the first time the window is opened after a
  -- login. A stored row carries no record of which source it came from, so
  -- staleness can only be decided once every source that COULD hold the name
  -- has answered.
  --
  -- ContactService decides that, per source, because it is the only thing that
  -- knows whether a request is still in flight. The old test here was "all five
  -- lists are non-empty", which is false forever for anyone with no guild, no
  -- friends or no mail history -- so RM_META_STALE, the single most useful
  -- sentence this window has, was invisible to most of the people it was
  -- written for.
  local sourcesComplete = true
  if CS and type(CS.SourcesReady) == "function" then
    local ok, ready = pcall(CS.SourcesReady)
    sourcesComplete = ok and ready and true or false
  end
  -- Set before the entry pass rather than after it: StaleFor reads it.
  RM._sourcesComplete = sourcesComplete

  local function Entry(key)
    local entry = byKey[key]
    if not entry then
      entry = { key = key, cats = {}, rank = RANK_SAVED }
      byKey[key] = entry
      entries[#entries + 1] = entry
    end
    return entry
  end

  for rank, bucket in ipairs(BUCKETS) do
    local list = buckets[bucket]
    if type(list) == "table" then
      for _, name in ipairs(list) do
        if type(name) == "string" and name ~= "" then
          local key = R.Key(name)
          if key ~= "" then
            local entry = Entry(key)
            entry.live = true
            entry.cats[bucket] = true
            -- Buckets already hold addresses in the source's own spelling
            -- (ContactService.BuildSuggestions), so this is a valid To: value
            -- as it stands. Recipients.Display would rebuild the same string
            -- from the key, but only by scanning every saved alt table, and
            -- that scan repeated once per guild member is not free.
            entry.liveName = entry.liveName or name
            if rank < entry.rank then
              entry.rank = rank
              entry.category = L[BUCKET_LABEL[bucket]]
            end
          end
        end
      end
    end
  end

  -- The curation overlay. Rows exist only for recipients that carry non-default
  -- state, so this ADDS the ones no live source returned (hidden alts from a
  -- realm you no longer play, manual additions, notes) and annotates the rest.
  R.ForEach(function(key, row)
    local entry = Entry(key)
    entry.hidden = row.hidden == true
    entry.fav    = row.fav == true
    entry.manual = row.manual == true
    entry.note   = (type(row.note) == "string" and row.note ~= "") and row.note or nil
  end)

  local hidden, favourites = 0, 0
  for _, entry in ipairs(entries) do
    if not entry.live then
      if entry.manual then
        entry.rank, entry.category = RANK_MANUAL, L["RM_CAT_MANUAL"]
      else
        entry.rank, entry.category = RANK_SAVED, L["RM_CAT_SAVED"]
      end
    end

    -- A stored row already carries its own casing, so Display is cheap for it.
    -- Everything else uses the name the live source gave us.
    if R.Get(entry.key) or not entry.liveName then
      entry.display = R.Display(entry.key)
    else
      entry.display = entry.liveName
    end
    if entry.display == "" then entry.display = entry.key end
    entry.search = Lower(entry.display)
    entry.sortName = entry.search

    local meta = R.AltMeta(entry.key)
    if type(meta) == "table" then
      entry.level    = tonumber(meta.level)
      entry.lastSeen = tonumber(meta.lastSeen)
      entry.faction  = (type(meta.faction) == "string" and meta.faction ~= "") and meta.faction or nil
    end

    entry.stale = StaleFor(entry)

    if entry.hidden then hidden = hidden + 1 end
    if entry.fav then favourites = favourites + 1 end
  end

  return entries, #entries, hidden, favourites
end

-------------------------------------------------------------
-- Filtering and sorting
-------------------------------------------------------------
local function ByName(a, b)
  if a.sortName == b.sortName then return a.key < b.key end
  return a.sortName < b.sortName
end

local function ByNameDesc(a, b)
  if a.sortName == b.sortName then return a.key > b.key end
  return a.sortName > b.sortName
end

-- The value each non-name sort orders by. Unknowns sort below everything in
-- ascending order (and therefore above it when reversed), which is where "no
-- data" belongs in both readings.
local SORT_VALUE = {
  category = function(entry) return entry.rank end,
  level    = function(entry) return entry.level or -1 end,
  lastSeen = function(entry) return entry.lastSeen or 0 end,
}

-- Reversing flips the PRIMARY comparison only; the name tiebreak stays A-Z in
-- both directions. Reversing the whole comparator instead would leave equal
-- levels reading Z-A, which looks like a second, unasked-for sort.
local function Comparator(field, descending)
  local value = SORT_VALUE[field]
  if not value then
    return descending and ByNameDesc or ByName
  end
  if descending then
    return function(a, b)
      local av, bv = value(a), value(b)
      if av ~= bv then return av > bv end
      return ByName(a, b)
    end
  end
  return function(a, b)
    local av, bv = value(a), value(b)
    if av ~= bv then return av < bv end
    return ByName(a, b)
  end
end

local function ActiveCategory()
  return CATEGORY_BY_ID[RM._filter or "all"] or CATEGORY_BY_ID.all
end

local function ApplyFilterAndSort()
  local entries = RM._entries or {}
  local query = Lower(Trim(RM._query or ""))
  local match = ActiveCategory().match
  local filtered = {}

  -- Category and search are one pass and both narrow: the category decides
  -- which names are on the table, the search narrows within them.
  for _, entry in ipairs(entries) do
    if (not match) or match(entry) then
      if query == "" or entry.search:find(query, 1, true) then
        filtered[#filtered + 1] = entry
      end
    end
  end

  table.sort(filtered, Comparator(RM._sort or "name", RM._sortDesc and true or false))
  RM._filtered = filtered
  return filtered
end

-- Per-category totals for the tile tooltips. Six predicates over the entry list
-- is a few thousand comparisons on a big guild -- cheap enough to redo whenever
-- the list changes, and it is the only way the counts can be trusted after a
-- bulk action.
local function CountCategories()
  local counts = {}
  local entries = RM._entries or {}

  for _, category in ipairs(CATEGORIES) do counts[category.id] = 0 end
  counts.all = #entries

  for _, entry in ipairs(entries) do
    for _, category in ipairs(CATEGORIES) do
      if category.match and category.match(entry) then
        counts[category.id] = counts[category.id] + 1
      end
    end
  end

  RM._catCounts = counts
  return counts
end

local function CountStates()
  local hidden, favourites = 0, 0
  for _, entry in ipairs(RM._entries or {}) do
    if entry.hidden then hidden = hidden + 1 end
    if entry.fav then favourites = favourites + 1 end
  end
  return hidden, favourites
end

-- Re-reads hidden/fav straight from the data layer. Used after a bulk action,
-- which is the one path that changes many rows at once without a full rescan.
local function SyncStates()
  local R = Recipients()
  if not R then return end
  for _, entry in ipairs(RM._entries or {}) do
    entry.hidden = R.IsHidden(entry.key)
    entry.fav = R.IsFavorite(entry.key)
    entry.stale = StaleFor(entry)
  end
end

-------------------------------------------------------------
-- Naming the current view
--
-- Every bulk action, tooltip and summary line describes the list the same way,
-- from one place. That matters most in the bulk confirmations: "Hide 148
-- recipients?" is a question nobody can answer safely, whereas "Hide 148
-- recipients? Showing: Guild" is.
-------------------------------------------------------------
local function CategoryLabel(id)
  local category = CATEGORY_BY_ID[id or "all"] or CATEGORY_BY_ID.all
  return L[category.labelKey]
end

-- The summary line does not wrap -- it must not change height, because the list
-- frame is anchored under it -- so the search term it quotes is capped. Cut on
-- a character boundary: chopping a multi-byte sequence in half renders as a
-- broken glyph.
local QUERY_DISPLAY_MAX = 24

local function ShortQuery(text)
  local length = #text
  local index, count = 1, 0
  while index <= length do
    if count == QUERY_DISPLAY_MAX then return text:sub(1, index - 1) .. "..." end
    local byte = text:byte(index)
    local size = 1
    if byte >= 240 then size = 4
    elseif byte >= 224 then size = 3
    elseif byte >= 192 then size = 2 end
    index = index + size
    count = count + 1
  end
  return text
end

-- A phrase naming what narrows the list, or nil when nothing does.
local function ScopeText()
  local query = Trim(RM._query or "")
  local id = RM._filter or "all"

  if id == "all" then
    if query == "" then return nil end
    return L("RM_SCOPE_SEARCH_ALL", ShortQuery(query))
  end
  if query == "" then return CategoryLabel(id) end
  return L("RM_SCOPE_SEARCH", CategoryLabel(id), ShortQuery(query))
end

-- The same phrase, but never nil: an unnarrowed list is "All".
local function ScopePhrase()
  return ScopeText() or CategoryLabel("all")
end

-------------------------------------------------------------
-- Row text
-------------------------------------------------------------
-- A line that appears on every one of several hundred rows has to carry
-- something that VARIES. Anything the whole list shares belongs in the header,
-- the tooltip, or nowhere -- which is why the old "no level or last-played
-- data" placeholder is gone: on a guild account it was three hundred identical
-- copies of a fact that can never change.
local function MetaText(entry)
  local parts = { entry.category or L["RM_CAT_SAVED"] }

  -- Class earns the space the placeholder used to waste: it differs row to row,
  -- and it is the one thing the class-coloured name fails to convey to anyone
  -- who does not already know the colours.
  local class = ClassName(entry.display)
  if class then parts[#parts + 1] = class end

  -- No "Favourites" segment. The star at the head of the row already says it,
  -- in the shape the whole addon uses for that fact, and a row that repeats it
  -- in words spends one of a handful of dense segments -- next to the class, the
  -- level and the last-played time, all of which vary -- restating something the
  -- eye has already read two inches to the left. A fact is stated once.
  if entry.level then parts[#parts + 1] = L("RM_META_LEVEL", entry.level) end
  local last = FormatLastSeen(entry.lastSeen)
  if last then parts[#parts + 1] = L("RM_META_LAST", last) end

  -- Said only where it can come true: one of the player's own characters, which
  -- records itself the next time it is played.
  if not entry.level and not last and TracksActivity(entry) then
    parts[#parts + 1] = L["RM_META_ALT_UNRECORDED"]
  end

  if entry.stale then
    parts[#parts + 1] = Theme.Colorize("warning", L["RM_META_STALE"])
  end

  local text = table.concat(parts, SEPARATOR)
  if entry.note then
    text = text .. "  " .. Theme.Colorize("accent", "\"" .. entry.note .. "\"")
  end
  return text
end

