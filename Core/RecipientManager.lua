-------------------------------------------------------------
-- Measuring and laying out the columns
--
-- RM.Measure reads the fonts in use (after a skin's fonts, a Text size, a
-- collect): the row's and the column names' heights, and each column's
-- width -- its widest cell over every entry, or its name. RM.Layout then
-- decides, for the row width the list has, which columns stand and where:
-- every column while the name keeps NAME_MIN, otherwise DROP's order,
-- re-decided on resize and never per row. A change of either moves
-- RM._lay.gen, and a row re-anchors its cells only when its gen is old.
-------------------------------------------------------------
local LAY = {
  gen = 0, rowW = 0, nameW = 0,
  shown = {}, x = {}, w = {},
  rowH = ROW.MIN_H, headH = ROW.HEAD_MIN,
  seen = {},           -- string -> its measured width, for one measuring pass
}
RM._lay = LAY

-- `frame.Probe` wears the cells' font, `frame.NameProbe` the name's.
function RM.Measure(frame)
  if not frame or not frame.Probe then return end
  local probe = frame.Probe
  local _, cellSize = probe:GetFont()
  local _, nameSize = frame.NameProbe:GetFont()
  local line = math.max(tonumber(cellSize) or 0, tonumber(nameSize) or 0)
  local rowH = math.max(ROW.MIN_H, math.ceil(line + ROW.AIR))
  local headH = math.max(ROW.HEAD_MIN, math.ceil((tonumber(cellSize) or 0) + ROW.HEAD_AIR))

  local w, seen = LAY.w, LAY.seen
  for s in pairs(seen) do seen[s] = nil end
  local entries = RM._entries or {}
  for c = 1, #COLS do
    local col = COLS[c]
    local cell = frame.HeadCells and frame.HeadCells[col.id]
    local width = math.ceil(Theme.TextWidth(cell))
    local field = col.field
    for i = 1, #entries do
      local s = entries[i][field]
      if s then
        local sw = seen[s]
        if not sw then
          probe:SetText(s)
          sw = math.ceil(Theme.TextWidth(probe))
          seen[s] = sw
        end
        if sw > width then width = sw end
      end
    end
    w[col.id] = width
  end
  probe:SetText("")

  LAY.rowH, LAY.headH = rowH, headH
  -- The next Layout decides again from these widths, whatever the row width.
  LAY.rowW = -1
end

-- rowW -> the columns that stand, their x from the row's left, the name's
-- width. Nothing is made; RM._lay is written in place.
function RM.Layout(rowW)
  rowW = math.floor(tonumber(rowW) or 0)
  if rowW <= 0 or rowW == LAY.rowW then return false end
  LAY.rowW = rowW
  local shown, w, x = LAY.shown, LAY.w, LAY.x
  local need = ROW.NAME_X + ROW.END_W
  for c = 1, #COLS do
    local id = COLS[c].id
    shown[id] = true
    need = need + (w[id] or 0) + ROW.GUTTER
  end
  local d = 1
  while rowW - need < ROW.NAME_MIN and DROP[d] do
    local id = DROP[d]
    shown[id] = false
    need = need - (w[id] or 0) - ROW.GUTTER
    d = d + 1
  end
  local right = rowW - ROW.END_W
  for c = #COLS, 1, -1 do
    local id = COLS[c].id
    if shown[id] then
      right = right - (w[id] or 0)
      x[id] = right
      right = right - ROW.GUTTER
    end
  end
  LAY.nameW = math.max(1, right - ROW.NAME_X)
  LAY.gen = LAY.gen + 1
  return true
end

-- The row width the content asks for with Category alone beside a name of
-- NAME_MIN: what the window's width floor stands on.
function RM.LeastRowWidth()
  return ROW.NAME_X + ROW.NAME_MIN + ROW.GUTTER + (LAY.w.category or 0) + ROW.END_W
end

-- One font string of a row or of the column names, placed as the layout says.
local function PlaceCell(fs, parent, id)
  local shown = LAY.shown[id]
  fs:SetShown(shown and true or false)
  if not shown then return end
  fs:ClearAllPoints()
  fs:SetPoint("LEFT", parent, "LEFT", LAY.x[id], 0)
  fs:SetWidth(LAY.w[id])
end

local function PlaceRowCells(row)
  row.Name:ClearAllPoints()
  row.Name:SetPoint("LEFT", row, "LEFT", ROW.NAME_X, 0)
  row.Name:SetWidth(LAY.nameW)
  for c = 1, #COLS do
    local id = COLS[c].id
    PlaceCell(row.Cells[id], row, id)
  end
  row._lgen = LAY.gen
end

-------------------------------------------------------------
-- Selection
--
-- The Mail tab's rules (CollectTab's SelectToggle / SelectRange): Ctrl-click
-- picks or unpicks one row and makes it the anchor; Shift-click picks every
-- row between the anchor and this one, or toggles this one when it is
-- already picked or nothing is; a plain click is never selection. Kept by
-- key, with the anchor a place in RM._filtered, and cleared whenever the
-- list's content changes under it (ApplyFilter) and on close.
-------------------------------------------------------------
local SEL = { set = {}, n = 0, anchor = nil }
RM._sel = SEL

local AfterSelectionChange

ClearSelection = function()
  if SEL.n == 0 and SEL.anchor == nil then return end
  for key in pairs(SEL.set) do SEL.set[key] = nil end
  SEL.n, SEL.anchor = 0, nil
  if AfterSelectionChange then AfterSelectionChange() end
end
RM.ClearSelection = ClearSelection

local function SetSelected(entry, on)
  local set = SEL.set
  if (set[entry.key] == true) == on then return end
  set[entry.key] = on or nil
  SEL.n = SEL.n + (on and 1 or -1)
end

function RM.SelectToggle(row)
  local entry = row and row._entry
  if not entry then return end
  SetSelected(entry, not SEL.set[entry.key])
  -- The row just picked is where the next shift-click measures from, picked
  -- or unpicked: the file manager's rule, and the Mail tab's.
  SEL.anchor = row._pos
  AfterSelectionChange()
end

function RM.SelectRange(row)
  local entry = row and row._entry
  if not entry then return end
  local anchor = SEL.anchor
  if SEL.set[entry.key] or not anchor or SEL.n == 0 then
    RM.SelectToggle(row)
    return
  end
  local from, to = anchor, row._pos or anchor
  if from > to then from, to = to, from end
  local filtered = RM._filtered
  for position = from, to do
    local at = filtered[position]
    if at then SetSelected(at, true) end
  end
  SEL.anchor = row._pos
  AfterSelectionChange()
end

-- The selected entries, in the list's order, into `out`.
local function SelectedEntries(out)
  Wipe(out)
  local filtered, set = RM._filtered, SEL.set
  for i = 1, #filtered do
    if set[filtered[i].key] then out[#out + 1] = filtered[i] end
  end
  return out
end

