    entry.stale = StaleFor(entry)
  end
end

-------------------------------------------------------------
-- Naming the current view
--
-- Every bulk action, tooltip and summary line describes the list the same way,
-- from one place. That matters most in the bulk confirmations: "Hide 148
-- recipients?" is a question nobody can answer safely, whereas "Hide 148
-- recipients? Showing: Guild" is.
-------------------------------------------------------------
local function CategoryLabel(id)
  local category = CATEGORY_BY_ID[id or "all"] or CATEGORY_BY_ID.all
  return L[category.labelKey]
end

-- The summary line does not wrap -- it must not change height, because the list
-- frame is anchored under it -- so the search term it quotes is capped. Cut on
-- a character boundary: chopping a multi-byte sequence in half renders as a
-- broken glyph.
local QUERY_DISPLAY_MAX = 24

local function ShortQuery(text)
  local length = #text
  local index, count = 1, 0
  while index <= length do
    if count == QUERY_DISPLAY_MAX then return text:sub(1, index - 1) .. "..." end
    local byte = text:byte(index)
    local size = 1
    if byte >= 240 then size = 4
    elseif byte >= 224 then size = 3
    elseif byte >= 192 then size = 2 end
    index = index + size
    count = count + 1
  end
  return text
end

-- A phrase naming what narrows the list, or nil when nothing does.
local function ScopeText()
  local query = Trim(RM._query or "")
  local id = RM._filter or "all"

  if id == "all" then
    if query == "" then return nil end
    return L("RM_SCOPE_SEARCH_ALL", ShortQuery(query))
  end
  if query == "" then return CategoryLabel(id) end
  return L("RM_SCOPE_SEARCH", CategoryLabel(id), ShortQuery(query))
end

-- The same phrase, but never nil: an unnarrowed list is "All".
local function ScopePhrase()
  return ScopeText() or CategoryLabel("all")
end

