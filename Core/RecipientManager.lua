local function BuildRow(parent)
  local row = CreateFrame("Button", nil, parent)
  row:SetHeight(LAY.rowH)
  row._h = LAY.rowH
  row:RegisterForClicks("LeftButtonUp", "RightButtonUp")

  -- Favourite. Icon-only, so deliberately NOT tagged __postboxButton: the skins
  -- only restyle the addon's push-buttons. It takes both buttons and hands
  -- them to the row, so a right-click on the star hides as anywhere else.
  row.Fav = CreateFrame("Button", nil, row)
  row.Fav:SetSize(ROW.STAR_HIT, ROW.STAR_HIT)
  row.Fav:SetPoint("LEFT", row, "LEFT", ROW.STAR_LEFT, 0)
  row.Fav:RegisterForClicks("LeftButtonUp", "RightButtonUp")
  row.Fav._row = row
  row.Fav.Icon = row.Fav:CreateTexture(nil, "ARTWORK")
  row.Fav.Icon:SetSize(ROW.STAR_ICON, ROW.STAR_ICON)
  row.Fav.Icon:SetPoint("CENTER")
  SetStarArt(row.Fav.Icon, false)
  row.Fav:SetScript("OnClick", ROWS.StarClick)
  row.Fav:SetScript("OnEnter", ROWS.StarEnter)
  row.Fav:SetScript("OnLeave", ROWS.StarLeave)

  -- The marks, right to left from the row's end.
  row.CrossMark = BuildMark(row, "x", 16)
  row.CrossMark:SetPoint("RIGHT", row, "RIGHT", -ROW.MARK_EDGE, 0)
  row.EyeMark = BuildMark(row, "eye", 8)
  row.EyeMark:SetPoint("RIGHT", row.CrossMark, "LEFT", -ROW.MARK_GAP, 0)
  row.EyeMark._art = "eye"
  row.NoteMark = BuildMark(row, "note", 16)
  row.NoteMark:SetPoint("RIGHT", row.EyeMark, "LEFT", -ROW.MARK_GAP, 0)

  row.Name = Theme.CreateText(row, "bodySmall")
  row.Name:SetJustifyH("LEFT")
  row.Name:SetWordWrap(false)

  -- `secondary`, never the disabled font object: these are facts, not
  -- inactive text.
  row.Cells = {}
  for c = 1, #COLS do
    local col = COLS[c]
    local fs = Theme.CreateText(row, "secondary")
    fs:SetJustifyH(col.right and "RIGHT" or "LEFT")
    fs:SetWordWrap(false)
    row.Cells[col.id] = fs
  end

  row:SetScript("OnClick", ROWS.RowClick)
  row:SetScript("OnEnter", ROWS.RowEnter)
  row:SetScript("OnLeave", ROWS.RowLeave)
  return row
end

local function AcquireRow(index)
  local frame = RM._frame
  local row = RM._rows[index]
  if row then return row, false end
  row = BuildRow(frame.ListChild)
  RM._rows[index] = row
  return row, true
end

local function FillRow(row, entry, position)
  row._entry = entry
  row._pos = position
  ResolveDelete(entry)
  if row._lgen ~= LAY.gen then PlaceRowCells(row) end

  local hidden = entry.hidden
  row.Name:SetText(NameText(entry))
  -- A hidden name steps back as the Characters list's do: the disabled token
  -- at full strength, no class colour -- never its alpha alone.
  Ink(row.Name, hidden and "textDisabled" or "textPrimary")
  local cells = row.Cells
  for c = 1, #COLS do
    local col = COLS[c]
    local fs = cells[col.id]
    if LAY.shown[col.id] then
      fs:SetText(entry[col.field] or "")
      local token = "textSecondary"
      if hidden then
        token = "textDisabled"
      elseif col.id == "category" and entry.stale then
        token = "warning"
      end
      Ink(fs, token)
    end
  end

  PaintStar(row)
  PaintMarks(row)
  PaintSelection(row)

  -- Zebra striping keeps a dense list readable, from the row's DISPLAYED
  -- position, through the primitive the mail list uses; the wash follows the
  -- pointer (RowHover).
  Theme.StyleMailRow(row, position, row._hover)

  row:Show()
end

local function UpdateVisibleRows()
  local frame = RM._frame
  if not frame then return end

  local filtered = RM._filtered
  local scroll = frame.ListScroll
  local viewport = scroll:GetHeight() or 0
  local offset = scroll:GetVerticalScroll() or 0
  local rowH = LAY.rowH

  local first = math.max(1, math.floor(offset / rowH) + 1)
  local last = first - 1
  if viewport > 0 then
    last = math.min(#filtered, math.ceil((offset + viewport) / rowH))
  end

  local created = false
  local used = 0
  for index = first, last do
    used = used + 1
    local row, isNew = AcquireRow(used)
    created = created or isNew
    if row._h ~= rowH then
      row._h = rowH
      row:SetHeight(rowH)
    end
    -- TOPLEFT + TOPRIGHT, never LEFT/RIGHT: two corner points on the same edge
    -- fix the width and the top without also constraining the vertical centre,
    -- which would fight SetHeight.
    local y = -((index - 1) * rowH)
    row:ClearAllPoints()
    row:SetPoint("TOPLEFT", frame.ListChild, "TOPLEFT", 0, y)
    row:SetPoint("TOPRIGHT", frame.ListChild, "TOPRIGHT", 0, y)
    FillRow(row, filtered[index], index)
  end

  for index = used + 1, #RM._rows do
    local row = RM._rows[index]
    row._entry = nil
    row:Hide()
  end

  -- Rows built on this pass have never been through the skin.
  if created and ns.Skin and ns.Skin.Refresh then
    ns.Skin.Refresh(frame)
  end
end

-- The column names, placed as the rows are.
local function PlaceHeader(frame)
  local head = frame.Head
  if not head or head._lgen == LAY.gen then return end
  head._lgen = LAY.gen
  head:SetHeight(LAY.headH)
  head.Name:ClearAllPoints()
  head.Name:SetPoint("LEFT", head, "LEFT", ROW.NAME_X, 0)
  head.Name:SetWidth(LAY.nameW)
  for c = 1, #COLS do
    local id = COLS[c].id
    PlaceCell(frame.HeadCells[id], head, id)
  end
end

-- Laid out again for the width the rows have now; the rows on screen and the
-- column names follow when anything moved.
local function Relayout(frame)
  local width = frame.ListScroll:GetWidth() or 0
  if width <= 10 then return end
  if RM.Layout(width) then
    PlaceHeader(frame)
    UpdateVisibleRows()
  end
end
RM.Relayout = Relayout

-- Why a source category is empty, as a locale key, or nil for "no better answer
-- than the generic line". ContactService decides it.
local function SourceEmptyReason(source)
  if not source then return nil end
  local CS = ns.ContactService
  if not CS or type(CS.EmptyReason) ~= "function" then return nil end
  local ok, key = pcall(CS.EmptyReason, source)
  if ok and type(key) == "string" and key ~= "" then return key end
  return nil
end

-- What the list says when it has nothing to show. With several hundred
-- recipients an empty list is nearly always a filter the user forgot about, so
-- each case names the thing that emptied it and how to get out.
local function EmptyText(total)
  if total == 0 then return L["RM_EMPTY"] end

  local query = Trim(RM._query or "")
  local id = RM._filter or "all"

  if query ~= "" then
    if id == "all" then return L["EMPTY_LIST_SEARCH"] end
    return L["EMPTY_LIST_SEARCH"] .. "\n\n" .. L["RM_EMPTY_FILTER_HINT"]
  end
  if id == "favourites" then return L["RM_EMPTY_FAVOURITES"] end
  if id == "hidden" then return L["RM_EMPTY_HIDDEN"] end
  if id == "all" then return L["RM_EMPTY"] end

  local category = CATEGORY_BY_ID[id]
  local reason = SourceEmptyReason(category and category.source)
  if reason then return L[reason] .. "\n\n" .. L["RM_EMPTY_FILTER_HINT"] end
  return L("RM_EMPTY_FILTER", CategoryLabel(id))
end

local function CountStates()
  local hidden, favourites = 0, 0
  local entries = RM._entries or {}
  for i = 1, #entries do
    if entries[i].hidden then hidden = hidden + 1 end
    if entries[i].fav then favourites = favourites + 1 end
  end
  return hidden, favourites
end

local function UpdateSummary()
  local frame = RM._frame
  if not frame then return end

  local total = #(RM._entries or {})
  local shown = #RM._filtered
  local hidden, favourites = CountStates()
  local scope = ScopeText()

  local hiddenText = ns.Plural("RM_SUMMARY_HIDDEN", hidden)
  local favText = ns.Plural("RM_SUMMARY_FAVORITES", favourites)
  local totalText = ns.Plural("RM_SUMMARY_RECIPIENTS", total)
  if scope then
    frame.Summary:SetText(L("RM_SUMMARY_FILTERED", scope, shown, totalText, hiddenText, favText))
  else
    frame.Summary:SetText(L("RM_SUMMARY", totalText, hiddenText, favText))
  end

  if shown == 0 then
    -- A search's "Nothing matches." stands centred where the list is, as
    -- the other lists' does; the longer explanations read from the top left.
    local searched = total > 0 and Trim(RM._query or "") ~= ""
    if frame._emptyCentred ~= searched then
      frame._emptyCentred = searched
      frame.Empty:SetJustifyH(searched and "CENTER" or "LEFT")
      frame.Empty:SetJustifyV(searched and "MIDDLE" or "TOP")
    end
    frame.Empty:SetText(EmptyText(total))
    frame.Empty:Show()
  else
    frame.Empty:Hide()
  end
end

-- Repaints the category tiles: which ones a source switched off takes away,
-- which one is active, and which are empty.
local function UpdateCategoryBar()
  local frame = RM._frame
  if not frame or not frame.CategoryTiles then return end

  local counts = RM._catCounts
  local active = RM._filter or "all"
  local off = COLLECT.off

  for _, tile in ipairs(frame.CategoryTiles) do
    local category = CATEGORY_BY_ID[tile._catId]
    tile:SetShown(not (category.source and off[category.source]))
    tile._active = (tile._catId == active)
    tile._empty = (counts[tile._catId] or 0) == 0
    if tile._starTile then
      SetStarArt(tile.Icon, not tile._empty)
      SetTileCount(tile, counts[tile._catId] or 0)
    end
    StyleTile(tile)
  end

  if frame.LayoutCategoryBar then frame.LayoutCategoryBar() end

  -- The Send tab's star shows the same count from the same field, and this
  -- window can be open beside an open mailbox: told when a count it shows
  -- (or a hide that changes its lists) really moved, and not otherwise.
  local hidden, favourites = CountStates()
  local total = #(RM._entries or {})
  if hidden ~= RM._toldHidden or favourites ~= RM._toldFav or total ~= RM._toldTotal then
    RM._toldHidden, RM._toldFav, RM._toldTotal = hidden, favourites, total
    if ns.SendTab and ns.SendTab.RefreshRecipientBar then
      ns.SendTab.RefreshRecipientBar()
    end
  end
end

-- resetScroll: only on a filter/sort change. A hide toggle must not throw the
-- user back to the top of a 300-name list.
local function RelayoutList(resetScroll)
  local frame = RM._frame
  if not frame then return end

  local count = #RM._filtered
  local rowH = LAY.rowH
  -- The scroll frame has no width until the window has been laid out once, and
  -- a zero-width child makes every row invisible rather than merely narrow.
  local width = frame.ListScroll:GetWidth() or 0
  if width > 10 then frame.ListChild:SetWidth(width) end
  frame.ListChild:SetHeight(math.max(count * rowH, 1))

  -- Clamp before anything reads the offset: a filter can shrink the list
  -- under an offset that was valid a moment ago.
  local viewport = frame.ListScroll:GetHeight() or 0
  local maxScroll = math.max(0, (count * rowH) - viewport)
  if resetScroll then
    frame.ListScroll:SetVerticalScroll(0)
  elseif (frame.ListScroll:GetVerticalScroll() or 0) > maxScroll then
    frame.ListScroll:SetVerticalScroll(maxScroll)
  end

  if frame.ListScroll.UpdateScrollChildRect then frame.ListScroll:UpdateScrollChildRect() end
  if width > 10 then RM.Layout(width) end
  PlaceHeader(frame)
  UpdateSummary()
  UpdateVisibleRows()
end

-------------------------------------------------------------
-- The foot
--
-- With nothing selected: Add recipient, then "Hide all listed" and "Show all
-- listed", evened to the longest caption. With rows selected the bulk pair
-- gives way to "Favorite N", "Hide N selected" and "Delete N selected",
-- which act on the selection; Add recipient keeps its width.
-------------------------------------------------------------
local FOOT = {}

function FOOT.Update(frame)
  frame = frame or RM._frame
  if not frame or not frame.Foot then return end
  local foot = frame.Foot
  local n = SEL.n
  local selecting = n > 0
  if selecting then
    foot.fav.caption = ns.Plural("RM_SEL_FAVORITE", n)
    foot.hide.caption = ns.Plural("RM_SEL_HIDE", n)
    foot.delete.caption = ns.Plural("RM_SEL_DELETE", n)
  end
  if foot._selecting ~= selecting then
    foot._selecting = selecting
    foot.fav:SetShown(selecting)
    foot.hide:SetShown(selecting)
    foot.delete:SetShown(selecting)
    foot.hideAll:SetShown(not selecting)
    foot.showAll:SetShown(not selecting)
  end
  FOOT.Layout(frame)
end

function FOOT.Layout(frame)
  local foot = frame.Foot
  local width = frame:GetWidth() or DEFAULT_W
  -- PAD at the left, the resize grip's clearance at the right, and one gap of
  -- genuine separation between the add button and the bulk buttons.
  local available = width - PAD - GRIP_CLEAR - M.gap
  local opts = foot.opts
  -- The resting row always lays out first: it is what gives Add its width.
  Theme.LayoutRow(foot.rest, available, opts)
  local right = foot.restRight
  if foot._selecting then
    right = foot.sel
    local room = available - foot.add:GetWidth() - ACTION_GAP
    Theme.LayoutRow(right, room, opts)
  end
  local list = foot._selecting and foot.allSel or foot.rest
  for i = 1, #list do
    local button = list[i]
    Theme.FitText(button:GetFontString(), button:GetWidth() - M.gap, button.caption, button)
  end
  -- The right-hand group, from the grip leftwards.
  local nextOne
  for i = #right, 1, -1 do
    local button = right[i]
    button:ClearAllPoints()
    if nextOne then
      button:SetPoint("RIGHT", nextOne, "LEFT", -ACTION_GAP, 0)
    else
      button:SetPoint("BOTTOMRIGHT", frame, "BOTTOMRIGHT", -GRIP_CLEAR, FOOT_PAD)
    end
    nextOne = button
  end
end

AfterSelectionChange = function()
  local rows = RM._rows or {}
  for i = 1, #rows do
    if rows[i]._entry then PaintSelection(rows[i]) end
  end
  FOOT.Update()
end

