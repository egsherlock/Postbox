local function Build()
  if RM._frame then return RM._frame end

  RM._rows = RM._rows or {}
  RM._sort = RM._sort or "name"
  if RM._sortDesc == nil then
    RM._sortDesc = (SORT_BY_ID[RM._sort] and SORT_BY_ID[RM._sort].desc) and true or false
  end
  RM._filter = RM._filter or "all"
  RM._query = RM._query or ""

  -- The global name is required: Helpers.RegisterEscClose puts frame:GetName()
  -- into UISpecialFrames and silently does nothing for an anonymous frame.
  local frame = CreateFrame("Frame", "PostboxRecipientManagerFrame", UIParent,
                            "BasicFrameTemplateWithInset")
  frame:SetSize(DEFAULT_W, DEFAULT_H)
  frame:SetPoint("CENTER", UIParent, "CENTER", 0, 0)
  frame:SetFrameStrata("FULLSCREEN_DIALOG")
  frame:SetToplevel(true)
  frame:SetClampedToScreen(true)
  frame:EnableMouse(true)
  frame:SetMovable(true)
  frame:SetResizable(true)
  if frame.SetResizeBounds then
    frame:SetResizeBounds(MIN_W, MIN_H, MAX_W, MAX_H)
  elseif frame.SetMinResize then
    frame:SetMinResize(MIN_W, MIN_H)
    frame:SetMaxResize(MAX_W, MAX_H)
  end
  frame:RegisterForDrag("LeftButton")
  frame:SetScript("OnDragStart", frame.StartMoving)
  frame:SetScript("OnDragStop", frame.StopMovingOrSizing)
  frame:SetScript("OnMouseDown", function(self) self:Raise() end)
  frame:Hide()

  -- Deliberately no __pbEuiAlwaysOpaque: that exists so the options panel stays
  -- legible while the transparency slider behind it moves. This is a content
  -- window and follows the user's own opacity.
  if frame.TitleText then frame.TitleText:SetText(L["RM_TITLE"]) end
  Theme.ApplyFrameTheme(frame)
  ns.Core.UI.Helpers.RegisterEscClose(frame)

  -----------------------------------------------------------
  -- Header band
  --
  -- Search, sort and the category bar are one enclosed block rather than three
  -- widgets floating over the window's stone. The band is the theme's
  -- `controls` variant -- a quiet warm tint with a lighter border, so it reads
  -- as a divider rather than a panel, but opaque enough to hold the search
  -- text and the tile captions at any window transparency -- and it is tagged
  -- __postboxPanel so a host-UI skin restyles it along with the addon's other
  -- containers.
  -----------------------------------------------------------
  local band = CreateFrame("Frame", nil, frame, "BackdropTemplate")
  band:SetPoint("TOPLEFT", frame, "TOPLEFT", PAD, -28)
  band:SetPoint("TOPRIGHT", frame, "TOPRIGHT", -PAD, -28)
  band:SetHeight((BAND_PAD * 2) + CTRL_H + BAND_PAD + BAR_H)
  Theme.ApplyBand(band)
  frame.HeaderBand = band

  -----------------------------------------------------------
  -- Sort control (Postbox's own dropdown: no MenuUtil, see COMBAT_TAINT.md)
  --
  -- The label used to be a separate "Sort" caption sitting to the left of the
  -- toggle, which read as stray text. It is now inside the toggle -- the button
  -- says "Sort: Name" -- so the control is one object, and the direction lives
  -- in the arrow immediately beside it.
  -----------------------------------------------------------
  local sortGroup = CreateFrame("Frame", nil, band)
  sortGroup:SetSize(SORT_GROUP_W, CTRL_H)
  sortGroup:SetPoint("TOPRIGHT", band, "TOPRIGHT", -BAND_PAD - 1, -BAND_PAD)

  local sortItems = {}
  for index, sort in ipairs(SORTS) do
    sortItems[index] = { id = sort.id, name = L[sort.nameKey] }
  end

  local sortDrop = ns.Core.UI.Dropdown.Create(sortGroup, {
    items        = sortItems,
    toggleWidth  = SORT_TOGGLE_W,
    toggleHeight = SORT_TOGGLE_H,
    height       = CTRL_H,
    defaultId    = RM._sort,
  })
  sortDrop:SetWidth(SORT_TOGGLE_W)
  sortDrop:SetPoint("LEFT", sortGroup, "LEFT", 0, 0)
  frame.SortDropdown = sortDrop

  -- Reversal, the other half of the control. Clicking the arrow flips the
  -- direction; re-picking the field that is already selected flips it too,
  -- which is the idiom every sortable column header in the game uses.
  --
  -- The SAME widget class as the toggle it sits against, not a flat plate. The
  -- two are one control -- "sort by this field, in this direction" -- and a
  -- plate beside a push button reads as two, because on a stock UI the button
  -- carries UIPanelButtonTemplate's bevel and the plate is a flat fill. Same
  -- factory, same height, same __postboxButton tag, so both host-UI skins
  -- restyle the pair together instead of one of them.
  local sortDir = Theme.CreateButton(nil, sortGroup)
  sortDir:SetSize(SORT_DIR_W, SORT_TOGGLE_H)
  sortDir:SetPoint("RIGHT", sortGroup, "RIGHT", 0, 0)

  -- The glyph hangs off a child FRAME rather than off the button, and that is
  -- the whole reason it is visible at all.
  --
  -- Both host-UI skins clear a push button's stock art by sweeping its REGIONS:
  -- Core/Skin_EllesmereUI.lua's Button primitive walks GetRegions() and sets
  -- every texture it finds to alpha 0, and Core/Skin_ElvUI.lua hands the button
  -- to S:HandleButton with strip = true, which is StripTextures. An icon created
  -- on the button IS one of those regions, so from the moment this control
  -- stopped being a plate and became a real button the arrow was wiped the
  -- instant either skin ran -- a blank square with a working tooltip.
  --
  -- A child frame is not a region of its parent, so nothing sweeps it. It is
  -- mouse-transparent (frames take no input unless asked to), so the button
  -- still receives every click and hover. And it draws above every layer of the
  -- parent's art, which on a stock UI also puts the arrow over
  -- UIPanelButtonTemplate's bevel instead of into it.
  local glyph = CreateFrame("Frame", nil, sortDir)
  glyph:SetAllPoints(sortDir)
  -- Stated rather than left to the implicit parent+1: EllesmereUI's border
  -- primitive can add its own overlay frame to a widget it skins, and the glyph
  -- has to stay above whatever a host UI puts on top.
  glyph:SetFrameLevel(sortDir:GetFrameLevel() + 3)
  sortDir.Arrow = glyph:CreateTexture(nil, "OVERLAY")
  sortDir.Arrow:SetSize(SORT_DIR_GLYPH, SORT_DIR_GLYPH)
  sortDir.Arrow:SetPoint("CENTER")
  frame.SortDirection = sortDir

  local function SortDirectionText()
    local pair = SORT_DIRECTION_KEY[RM._sort or "name"] or SORT_DIRECTION_KEY.name
    return L[pair[RM._sortDesc and 2 or 1]]
  end

  -- One place decides what the whole control says, so the toggle caption, the
  -- arrow and the tooltip can never disagree about the current sort.
  function frame.RefreshSortControl()
    local sort = SORT_BY_ID[RM._sort or "name"] or SORTS[1]
    sortDrop:SetSelectedId(sort.id)
    sortDrop:SetText(L("RM_SORT_TOGGLE", L[sort.nameKey]))
    SetArrowArt(sortDir.Arrow, not RM._sortDesc)
    -- After the art, and on every refresh rather than once at build. The glyph
    -- reads as this control's caption, so it takes the caption's loud tone
    -- rather than a warm off-white chosen here -- and a TEXTURE carries no token
    -- for Theme.RepaintAccentText to find, so re-asserting it here is what keeps
    -- it on the LIVE accent after an EllesmereUI user retunes theirs.
    Theme.SetColor(sortDir.Arrow, "accentBright")
  end

  sortDrop:SetChangeCallback(function(id)
    RM.SetSort(id, true)
  end)

  -- SetScript, not the plate factory's `_onEnter` slot: this is a push button
  -- now, and it has no plate art to repaint on hover -- the template's own
  -- highlight does that.
  sortDir:SetScript("OnEnter", function(self)
    GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
    GameTooltip:SetText(L["RM_SORT_LABEL"])
    GameTooltip:AddLine(SortDirectionText(), 1, 1, 1, true)
    GameTooltip:AddLine(L["RM_SORT_DIR_TIP"], 0.7, 0.7, 0.7, true)
    GameTooltip:Show()
  end)
  sortDir:SetScript("OnLeave", function() GameTooltip:Hide() end)
  sortDir:SetScript("OnClick", function()
    RM.SetSort(RM._sort, true)
    ToggleSound(not RM._sortDesc)
  end)

  frame.RefreshSortControl()

  -----------------------------------------------------------
  -- Search box
  -----------------------------------------------------------
  local searchWrap = CreateFrame("Frame", nil, band, "BackdropTemplate")
  searchWrap:SetHeight(CTRL_H)
  searchWrap:SetPoint("TOPLEFT", band, "TOPLEFT", BAND_PAD + 1, -BAND_PAD)
  searchWrap:SetPoint("RIGHT", sortGroup, "LEFT", -8, 0)
  Theme.StyleInput(searchWrap)
  searchWrap.__postboxInputWrap = true

  local searchBox = CreateFrame("EditBox", nil, searchWrap)
  searchBox:SetAutoFocus(false)
  local searchFont = Theme.FontObject("bodySmall")
  if searchFont then searchBox:SetFontObject(searchFont) end
  Theme.SetColor(searchBox, "textPrimary")
  searchBox:SetPoint("TOPLEFT", searchWrap, "TOPLEFT", 8, -4)
  searchBox:SetPoint("BOTTOMRIGHT", searchWrap, "BOTTOMRIGHT", -6, 4)
  -- The wrap carries the backdrop; skinning the inner box as well would double
  -- the border.
  searchBox.__postboxNoEditSkin = true
  searchBox:SetScript("OnEscapePressed", function(self)
    self:SetText("")
    self:ClearFocus()
  end)
  searchWrap:SetScript("OnMouseDown", function() searchBox:SetFocus() end)
  frame.SearchBox = searchBox

  local searchPH = Theme.CreateText(searchWrap, "placeholder")
  searchPH:SetPoint("TOPLEFT", searchWrap, "TOPLEFT", 8, -4)
  searchPH:SetPoint("BOTTOMRIGHT", searchWrap, "BOTTOMRIGHT", -8, 4)
  searchPH:SetJustifyH("LEFT")
  searchPH:SetJustifyV("MIDDLE")
  searchPH:SetText(L["RM_SEARCH_PLACEHOLDER"])

  searchBox:SetScript("OnTextChanged", function(self)
    local text = self:GetText() or ""
    searchPH:SetShown(text == "")
    RM._query = text
    ApplyFilterAndSort()
    RelayoutList(true)
  end)

  -----------------------------------------------------------
  -- Category bar
  --
  -- Favourites is a star tile on the left, exactly as on the Send tab: seven
  -- equal word tiles would take each one to ~65px at the minimum window width,
  -- and these labels do not word-wrap, so a long translation would clip rather
  -- than ellipsize. The remaining six share the rest evenly, and their edges are
  -- derived from the usable width rather than from a rounded per-tile width, so
  -- the last tile always meets the right edge.
  --
  -- The star tile is the one whose width is not fixed: it grows by the width of
  -- its favourite count, at most three characters. That is ~4px off each word
  -- tile at the minimum window size, which those six have to spare -- and it is
  -- read from the tile rather than assumed, so the two can never drift apart.
  -----------------------------------------------------------
  local catBar = CreateFrame("Frame", nil, band)
  catBar:SetHeight(BAR_H)
  catBar:SetPoint("TOPLEFT", searchWrap, "BOTTOMLEFT", 0, -BAND_PAD)
  catBar:SetPoint("RIGHT", sortGroup, "RIGHT", 0, 0)
  frame.CategoryBar = catBar
  frame.CategoryTiles = {}

  local wordTiles = {}

  local function LayoutCategoryBar()
    local width = catBar:GetWidth() or 0
    if width < 60 or #wordTiles == 0 then return end
    -- The star tile's width tracks its favourite count, so read it rather than
    -- assuming the no-count width.
    local left = ((frame.StarTile and frame.StarTile:GetWidth()) or BAR_STAR_W) + BAR_GAP
    local usable = width - left
    local function edge(index)
      return left + math.floor((index * usable / #wordTiles) + 0.5)
    end
    for index, tile in ipairs(wordTiles) do
      tile:ClearAllPoints()
      tile:SetWidth(math.max(1, edge(index) - edge(index - 1) - BAR_GAP))
      tile:SetPoint("TOPLEFT", catBar, "TOPLEFT", edge(index - 1), 0)
    end
  end

  for _, category in ipairs(CATEGORIES) do
    local tile = CreateTile(catBar, "segment")
    tile._catId = category.id

    if category.star then
      tile._starTile = true
      tile:SetWidth(BAR_STAR_W)
      tile:SetPoint("TOPLEFT", catBar, "TOPLEFT", 0, 0)
      tile.Icon = tile:CreateTexture(nil, "ARTWORK")
      tile.Icon:SetSize(BAR_STAR_ICON, BAR_STAR_ICON)
      -- LEFT-anchored rather than centred, so the star does not shift sideways
      -- when a count appears next to it.
      tile.Icon:SetPoint("LEFT", tile, "LEFT", BAR_STAR_PAD, 0)
      -- UpdateCategoryBar picks the real state; this is only the first draw.
      SetStarArt(tile.Icon, false)

      -- Gold, and only on screen when there is something to count. No fixed
      -- width and no wrap: the string sizes itself and the tile is measured
      -- from it, which is the combination that cannot clip. The accent is the
      -- live one, exactly as on the Send tab's star.
      tile.Count = Theme.CreateText(tile, "bodySmall")
      tile.Count:SetPoint("LEFT", tile.Icon, "RIGHT", BAR_COUNT_GAP, 0)
      tile.Count:SetJustifyH("LEFT")
      tile.Count:SetWordWrap(false)
      Theme.SetColor(tile.Count, "accent")
      tile.Count:Hide()
      frame.StarTile = tile
    else
      -- The plate already owns a centred, unwrapped, registered font string in
      -- the `segment` text role, so SetText drives it.
      tile:SetText(L[category.labelKey])
      wordTiles[#wordTiles + 1] = tile
    end

    tile._onEnter = function(self)
      local counts = RM._catCounts or {}
      local count = counts[category.id] or 0
      GameTooltip:SetOwner(self, "ANCHOR_BOTTOM")
      -- The star tile has no label on screen, so the title is the only place
      -- its name is ever said.
      GameTooltip:SetText(L[category.labelKey])
      GameTooltip:AddLine(L("RM_CAT_TIP_COUNT", count, #(RM._entries or {})), 1, 1, 1)
      GameTooltip:AddLine(L["RM_CAT_TIP_HINT"], 0.7, 0.7, 0.7, true)
      -- Empty is not a dead end: say how to fill it.
      if category.star and count == 0 then
        GameTooltip:AddLine(L["RM_CAT_TIP_FAV_EMPTY"], 0.7, 0.7, 0.7, true)
      end
      -- An empty source category says why here too, not only once you have
      -- clicked it and are looking at a blank list.
      if count == 0 and category.source then
        local reason = SourceEmptyReason(category.source)
        if reason then GameTooltip:AddLine(L[reason], 0.7, 0.7, 0.7, true) end
      end
      GameTooltip:Show()
    end
    tile:SetScript("OnClick", function(self)
      RM.SetFilter(self._catId)
      ToggleSound(true)
    end)

    frame.CategoryTiles[#frame.CategoryTiles + 1] = tile
  end

  -- UpdateCategoryBar re-tiles the bar whenever the favourite count changes the
  -- star tile's width, so it needs the layout pass by name.
  frame.LayoutCategoryBar = LayoutCategoryBar
  catBar:SetScript("OnSizeChanged", LayoutCategoryBar)
  LayoutCategoryBar()

  -----------------------------------------------------------
  -- Summary line
  --
  -- Sits between the band and the list because that is what it describes: on a
  -- 300-name account it is the sentence that explains why the list below is
  -- twelve rows long.
  -----------------------------------------------------------
  -- Two top corners, not TOPLEFT + RIGHT: a RIGHT anchor also fixes the
  -- vertical centre, which fights the top and leaves the string's rect
  -- ambiguous -- and the list frame below is anchored to that rect.
  -- `secondary`, not the disabled font object: this sentence is the one that
  -- explains why the list below is twelve rows long, and it is never inactive.
  frame.Summary = Theme.CreateText(frame, "secondary")
  frame.Summary:SetPoint("TOPLEFT", band, "BOTTOMLEFT", 2, -6)
  frame.Summary:SetPoint("TOPRIGHT", band, "BOTTOMRIGHT", -2, -6)
  frame.Summary:SetJustifyH("LEFT")
  frame.Summary:SetWordWrap(false)
  frame.Summary:SetText("")

  -----------------------------------------------------------
  -- Bottom action bar
  -----------------------------------------------------------
  local addButton = Theme.CreateButton(nil, frame)
  addButton:SetHeight(CTRL_H)
  addButton:SetPoint("BOTTOMLEFT", frame, "BOTTOMLEFT", PAD, 10)
  addButton.caption = L["RM_BTN_ADD"]
  addButton:SetText(addButton.caption)
  addButton:SetScript("OnClick", function()
    if not EnsureAddDialog() or type(StaticPopup_Show) ~= "function" then return end
    StaticPopup_Show(ADD_POPUP, L["RM_ADD_TITLE"])
  end)

  -- Right-most control stops short of the resize grip in the corner.
  local showAll = Theme.CreateButton(nil, frame)
  showAll:SetHeight(CTRL_H)
  showAll:SetPoint("BOTTOMRIGHT", frame, "BOTTOMRIGHT", -26, 10)
  showAll.caption = L["RM_BTN_SHOW_ALL"]
  showAll:SetText(showAll.caption)
  showAll:SetScript("OnClick", function() RM.Bulk(false) end)

  local hideAll = Theme.CreateButton(nil, frame)
  hideAll:SetHeight(CTRL_H)
  hideAll:SetPoint("RIGHT", showAll, "LEFT", -ACTION_GAP, 0)
  hideAll.caption = L["RM_BTN_HIDE_ALL"]
  hideAll:SetText(hideAll.caption)
  hideAll:SetScript("OnClick", function() RM.Bulk(true) end)

  -- Measured, and re-measured on resize. All three were 130px wide around
  -- captions that come out of a locale file: "Alle aufgelisteten ausblenden" and
  -- the Russian equivalent are both far wider than "Hide all listed" and simply
  -- ran off the end of the button. LayoutRow evens them to the longest, drops to
  -- the minimum padding if that does not fit, and only then narrows them -- at
  -- which point FitText ellipsizes and the tooltip carries the full caption, so
  -- nothing is ever silently clipped.
  local actionButtons = { addButton, hideAll, showAll }

  local function LayoutActionBar()
    -- PAD at the left, the resize grip's clearance at the right, and one gap of
    -- genuine separation between the add button and the bulk pair.
    local available = (frame:GetWidth() or DEFAULT_W) - PAD - 26 - M.gap
    Theme.LayoutRow(actionButtons, available, {
      height = CTRL_H, gap = ACTION_GAP, maxLines = 1, truncate = true,
      minWidth = M.buttonMinWidth,
    })
    for index = 1, #actionButtons do
      local button = actionButtons[index]
      Theme.FitText(button:GetFontString(), button:GetWidth() - M.gap,
                    button.caption, button)
    end
  end

  frame.LayoutActionBar = LayoutActionBar
  LayoutActionBar()
  -- HookScript: the window persistence layer installs its own size handler and
  -- replacing it would stop the saved size being written.
  frame:HookScript("OnSizeChanged", LayoutActionBar)

  addButton:SetScript("OnEnter", function(self)
    if not self.__pbOverflowText then return end
    GameTooltip:SetOwner(self, "ANCHOR_TOP")
    GameTooltip:ClearLines()
    Theme.AddOverflowLine(self, GameTooltip)
    GameTooltip:Show()
  end)
  addButton:SetScript("OnLeave", function() GameTooltip:Hide() end)

  -- The tooltip names the set the button would act on, because "all listed" is
  -- only meaningful once you know what is currently listed. It reads `caption`
  -- rather than GetText, which may have been ellipsized to fit.
  for _, button in ipairs({ hideAll, showAll }) do
    button:SetScript("OnEnter", function(self)
      GameTooltip:SetOwner(self, "ANCHOR_TOP")
      GameTooltip:SetText(self.caption)
      GameTooltip:AddLine(L("RM_TIP_BULK", #(RM._filtered or {}), ScopePhrase()), 1, 1, 1, true)
      GameTooltip:Show()
    end)
    button:SetScript("OnLeave", function() GameTooltip:Hide() end)
  end

  -----------------------------------------------------------
  -- List
  -----------------------------------------------------------
  local listArea = CreateFrame("Frame", nil, frame, "BackdropTemplate")
  -- Anchored under the summary rather than at a fixed offset, so the header can
  -- change height without a second number needing to be kept in step with it.
  listArea:SetPoint("TOPLEFT", frame.Summary, "BOTTOMLEFT", -2, -6)
  listArea:SetPoint("RIGHT", frame, "RIGHT", -PAD, 0)
  listArea:SetPoint("BOTTOM", addButton, "TOP", 0, 8)
  Theme.ApplyList(listArea)
  frame.ListArea = listArea

  -- UIPanelScrollFrameTemplate specifically: both skins special-case its
  -- classic slider scroll bar.
  local scroll = CreateFrame("ScrollFrame", nil, listArea, "UIPanelScrollFrameTemplate")
  scroll:SetPoint("TOPLEFT", listArea, "TOPLEFT", LIST_INSET, -LIST_INSET)
  -- One gutter width for every scroll frame in the addon, wide enough that the
  -- classic bar clears the container's border art. It was 22 here, which is the
  -- one width that put the bar ON that art.
  scroll:SetPoint("BOTTOMRIGHT", listArea, "BOTTOMRIGHT", -M.scrollGutter, LIST_INSET)
  frame.ListScroll = scroll

  local child = CreateFrame("Frame", nil, scroll)
  child:SetSize(math.max(scroll:GetWidth() or 0, 100), 1)
  scroll:SetScrollChild(child)
  frame.ListChild = child

  -- HookScript, not SetScript: the template installs its own handlers here and
  -- replacing them desynchronises the scroll bar.
  scroll:HookScript("OnSizeChanged", function(self, width)
    if width and width > 10 then child:SetWidth(width) end
    UpdateVisibleRows()
  end)
  scroll:HookScript("OnVerticalScroll", function() UpdateVisibleRows() end)

  frame.Empty = Theme.CreateText(listArea, "secondary")
  frame.Empty:SetPoint("TOPLEFT", listArea, "TOPLEFT", 24, -40)
  frame.Empty:SetPoint("BOTTOMRIGHT", listArea, "BOTTOMRIGHT", -24, 24)
  frame.Empty:SetJustifyH("LEFT")
  frame.Empty:SetJustifyV("TOP")
  frame.Empty:SetWordWrap(true)
  frame.Empty:Hide()

  -----------------------------------------------------------
  -- Position / size persistence
  -----------------------------------------------------------
  local store = ns.Store.EnsurePath("profile.rmWindow", {})
  -- The header grew a row, so the minimum window height did too. A size stored
  -- under the old floor would be restored verbatim (persistence clamps on save,
  -- not on restore) and hand back a two-row list; raise it here instead.
  if type(store.width) == "number" and store.width < MIN_W then store.width = MIN_W end
  if type(store.height) == "number" and store.height < MIN_H then store.height = MIN_H end

  frame.ResizeButton = ns.Core.UI.Helpers.CreateResizeButton(frame, function(f)
    ns.Core.UI.Helpers.SaveFramePosition(f, store)
    UpdateVisibleRows()
  end)
  -- After the frame's own OnDragStop is set: ApplyWindowPersistence wraps it.
  ns.Core.UI.Helpers.ApplyWindowPersistence(frame, store, {
    minW = MIN_W, maxW = MAX_W, minH = MIN_H, maxH = MAX_H,
  })

  RM._frame = frame

  -- ApplyWindow only exists in the EllesmereUI skin; without the Apply fallback
  -- ElvUI users would get an unskinned window.
  if ns.Skin then (ns.Skin.ApplyWindow or ns.Skin.Apply)(frame) end

  return frame
end

-------------------------------------------------------------
-- Public API
-------------------------------------------------------------
function RM.Show()
  local frame = Build()
  if not frame:IsShown() then
    -- Never leave the sort list and the Send tab's contact picker open at once.
    if ns.Core.UI.Dropdown and ns.Core.UI.Dropdown.CloseAll then
      ns.Core.UI.Dropdown.CloseAll()
    end
    frame:Show()
  end
  RM.Refresh()
  frame:Raise()
  if ns.Skin and ns.Skin.Refresh then ns.Skin.Refresh(frame) end
end

function RM.Hide()
  if RM._frame then RM._frame:Hide() end
end

function RM.IsShown()
  return RM._frame ~= nil and RM._frame:IsShown()
end

function RM.Toggle()
  local frame = Build()
  if frame:IsShown() then
    frame:Hide()
    return
  end
  RM.Show()
end
