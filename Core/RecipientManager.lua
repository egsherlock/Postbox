    or L("RM_DELETE_CONFIRM", name)
  Theme.LiftPopup(StaticPopup_Show(DELETE_POPUP, text, nil,
                                   { key = key, display = display, unlisted = unlisted }))
end

function RM.DeleteRecipient(key, display, unlisted)
