    local head = entry.category or L["RM_CAT_SAVED"]
    local class = ClassName(entry.display)
    if class then head = head .. SEPARATOR .. class end
    GameTooltip:AddLine(head, 0.7, 0.7, 0.7)
    if entry.level then GameTooltip:AddLine(L("RM_META_LEVEL", entry.level), 1, 1, 1) end
    local last = FormatLastSeen(entry.lastSeen)
    if last then GameTooltip:AddLine(L("RM_META_LAST", last), 1, 1, 1) end
    -- The tooltip is where the explanation belongs; the row itself gets the
    -- four-word version, and everyone whose level can never be known gets
    -- neither.
    if not entry.level and not last and TracksActivity(entry) then
      GameTooltip:AddLine(L["RM_TIP_ALT_UNRECORDED"], 0.7, 0.7, 0.7, true)
    end
    if entry.note then GameTooltip:AddLine("\"" .. entry.note .. "\"", 0.83, 0.64, 0.29, true) end
    if entry.stale then GameTooltip:AddLine(L["RM_TIP_STALE"], 1, 0.6, 0.25, true) end
    -- The same gesture, said the same way, as the Send tab's contact picker.
    GameTooltip:AddLine(L["RM_TIP_ROW_FAV"], 0.5, 0.5, 0.5, true)
    GameTooltip:Show()
  end)
  row:SetScript("OnLeave", function() GameTooltip:Hide() end)

  return row
end

local function AcquireRow(index)
  local frame = RM._frame
  local row = RM._rows[index]
  if row then return row, false end
  row = BuildRow(frame.ListChild)
  RM._rows[index] = row
  return row, true
end

-- Resolved on first render and cached on the entry. CanDelete walks the mail
-- history and every saved alt table, which is far too much to pay for several
-- hundred recipients when only a screenful is ever on show. Every path that can
-- change the answer (delete, manual add) rebuilds the entries outright.
local function ResolveDelete(entry)
  if entry.deleteChecked then return end
  entry.deleteChecked = true
  local R = Recipients()
  if not R then
    entry.canDelete, entry.deleteReason = false, "RM_ERR_LIVE_ONLY"
    return
  end
  local canDelete, reason = R.CanDelete(entry.key)
  entry.canDelete = canDelete and true or false
  entry.deleteReason = (not canDelete) and (reason or "RM_ERR_LIVE_ONLY") or nil
end

local function FillRow(row, entry, absoluteIndex)
  row._entry = entry
  ResolveDelete(entry)

  row.Name:SetText(DecorateName(entry.display))
  row.Meta:SetText(MetaText(entry))

  local dim = entry.hidden and 0.45 or 1
  row.Name:SetAlpha(dim)
  row.Meta:SetAlpha(dim)

  SetStarArt(row.Fav.Icon, entry.fav and true or false)

  row.HideCheck:SetChecked(entry.hidden and true or false)

  if entry.canDelete then row.Delete:Enable() else row.Delete:Disable() end

  -- Zebra striping keeps a dense two-line row readable. Painted through the
  -- same primitive the mail list uses, from the row's DISPLAYED position, so
  -- the two lists stripe alike; hover is a HIGHLIGHT texture on this row rather
  -- than a repaint, hence the constant `false`.
  Theme.StyleMailRow(row, absoluteIndex, false)

  row:Show()
end

local function UpdateVisibleRows()
  local frame = RM._frame
  if not frame then return end

  local filtered = RM._filtered or {}
  local scroll = frame.ListScroll
  local viewport = scroll:GetHeight() or 0
  local offset = scroll:GetVerticalScroll() or 0

  local first = math.max(1, math.floor(offset / ROW_H) + 1)
  local last = first - 1
  if viewport > 0 then
    last = math.min(#filtered, math.ceil((offset + viewport) / ROW_H))
  end

  local created = false
  local used = 0
  for index = first, last do
    used = used + 1
    local row, isNew = AcquireRow(used)
    created = created or isNew
    -- TOPLEFT + TOPRIGHT, never LEFT/RIGHT: two corner points on the same edge
    -- fix the width and the top without also constraining the vertical centre,
    -- which would fight SetHeight.
    local y = -((index - 1) * ROW_H)
    row:ClearAllPoints()
    row:SetPoint("TOPLEFT", frame.ListChild, "TOPLEFT", 0, y)
    row:SetPoint("TOPRIGHT", frame.ListChild, "TOPRIGHT", 0, y)
    FillRow(row, filtered[index], index)
  end

  for index = used + 1, #RM._rows do
    local row = RM._rows[index]
    row._entry = nil
    row:Hide()
  end

  -- Rows built on this pass have never been through the skin.
  if created and ns.Skin and ns.Skin.Refresh then
    ns.Skin.Refresh(frame)
  end
end

-- Why a source category is empty, as a locale key, or nil for "no better answer
-- than the generic line".
--
-- ContactService decides it, because it is the only thing that knows whether a
-- guild roster request is still in flight. The Send tab's picker asks the same
-- question of the same function, so the two windows cannot end up explaining the
-- same empty list differently.
local function SourceEmptyReason(source)
  if not source then return nil end
  local CS = ns.ContactService
  if not CS or type(CS.EmptyReason) ~= "function" then return nil end
  local ok, key = pcall(CS.EmptyReason, source)
  if ok and type(key) == "string" and key ~= "" then return key end
  return nil
end

-- What the list says when it has nothing to show. With several hundred
-- recipients an empty list is nearly always a filter the user forgot about, so
-- each case names the thing that emptied it and how to get out.
local function EmptyText(total)
  if total == 0 then return L["RM_EMPTY"] end

  local query = Trim(RM._query or "")
  local id = RM._filter or "all"

  if query ~= "" then
    if id == "all" then return L("RM_EMPTY_SEARCH", ShortQuery(query)) end
    return L("RM_EMPTY_SEARCH_FILTER", ShortQuery(query), CategoryLabel(id))
  end
  if id == "favourites" then return L["RM_EMPTY_FAVOURITES"] end
  if id == "hidden" then return L["RM_EMPTY_HIDDEN"] end
  if id == "all" then return L["RM_EMPTY"] end

  -- "Nothing in Guild" is true and useless to somebody who is not in a guild,
  -- and worse than useless during the roster round trip on a cold login. Where
  -- the reason is knowable it leads, and the way out follows it.
  local category = CATEGORY_BY_ID[id]
  local reason = SourceEmptyReason(category and category.source)
  if reason then return L[reason] .. "\n\n" .. L["RM_EMPTY_FILTER_HINT"] end
  return L("RM_EMPTY_FILTER", CategoryLabel(id))
end

local function UpdateSummary()
  local frame = RM._frame
  if not frame then return end

  local total = #(RM._entries or {})
  local shown = #(RM._filtered or {})
  local hidden, favourites = CountStates()
  local scope = ScopeText()

  if scope then
    frame.Summary:SetText(L("RM_SUMMARY_FILTERED", scope, shown, total, hidden, favourites))
  else
    frame.Summary:SetText(L("RM_SUMMARY", total, hidden, favourites))
  end

  if shown == 0 then
    frame.Empty:SetText(EmptyText(total))
    frame.Empty:Show()
  else
    frame.Empty:Hide()
  end
end

-- Repaints the category tiles: which one is active, and which are empty.
local function UpdateCategoryBar()
  local frame = RM._frame
  if not frame or not frame.CategoryTiles then return end

  local counts = RM._catCounts or {}
  local active = RM._filter or "all"

  for _, tile in ipairs(frame.CategoryTiles) do
    tile._active = (tile._catId == active)
    tile._empty = (counts[tile._catId] or 0) == 0
    if tile._starTile then
      -- Filled gold plus the number when there are favourites, hollow outline
      -- and no number when there are none. The two states then differ in shape,
      -- in colour and in content -- not in how faded the same glyph is.
      SetStarArt(tile.Icon, not tile._empty)
      SetTileCount(tile, counts[tile._catId] or 0)
    end
    StyleTile(tile)
  end

  -- The star tile's width is the word tiles' left edge, so a changed count
  -- re-tiles the rest of the bar.
  if frame.LayoutCategoryBar then frame.LayoutCategoryBar() end

  -- The Send tab's star shows the same count from the same field, and this
  -- window can be open beside an open mailbox. Every path that changes a
  -- favourite comes through here, so this is the one place the other window has
  -- to be told.
  if ns.SendTab and ns.SendTab.RefreshRecipientBar then
    ns.SendTab.RefreshRecipientBar()
  end
end

-- resetScroll: only on a filter/sort change. A hide toggle must not throw the
-- user back to the top of a 300-name list.
local function RelayoutList(resetScroll)
  local frame = RM._frame
  if not frame then return end

  local count = #(RM._filtered or {})
  -- The scroll frame has no width until the window has been laid out once, and
  -- a zero-width child makes every row invisible rather than merely narrow.
  local width = frame.ListScroll:GetWidth() or 0
  if width > 10 then frame.ListChild:SetWidth(width) end
  frame.ListChild:SetHeight(math.max(count * ROW_H, 1))

  -- A category filter can shrink the list under a scroll offset that was valid
  -- a moment ago. The scroll frame keeps that offset, UpdateVisibleRows then
  -- computes a first row past the end of the filtered set, and the viewport
  -- goes blank with a scroll bar that still thinks it has somewhere to go.
  -- Clamp before anything reads the offset.
  local viewport = frame.ListScroll:GetHeight() or 0
  local maxScroll = math.max(0, (count * ROW_H) - viewport)
  if resetScroll then
    frame.ListScroll:SetVerticalScroll(0)
  elseif (frame.ListScroll:GetVerticalScroll() or 0) > maxScroll then
    frame.ListScroll:SetVerticalScroll(maxScroll)
  end

  if frame.ListScroll.UpdateScrollChildRect then frame.ListScroll:UpdateScrollChildRect() end
  UpdateCategoryBar()
  UpdateSummary()
  UpdateVisibleRows()
end

