-- State-only redraw: no source rescan, so a checkbox click does not trigger a
-- guild roster pass.
--
-- Under Favourites or Hidden the changed row has just left the list it is
-- sitting in, so those two re-filter instead. Scroll position is kept: the user
-- is working down a list and being thrown back to the top after every tick is
-- worse than the row vanishing under the cursor, which is what they asked for.
function RM.SoftRefresh()
  if not RM._frame then return end

  CountCategories()
  if STATEFUL_FILTERS[RM._filter or "all"] then
    ApplyFilterAndSort()
    RelayoutList(false)
    return
  end

  UpdateCategoryBar()
  UpdateSummary()
  UpdateVisibleRows()
end

function RM.Refresh(resetScroll)
  if not RM._frame then return end
  RM._entries = Collect()
  CountCategories()
  ApplyFilterAndSort()
  RelayoutList(resetScroll)
end

-- Switches the active category. Scroll resets: the list underneath is a
-- different set of names, so keeping the offset would land the user in an
-- arbitrary place in it.
function RM.SetFilter(id)
  local category = CATEGORY_BY_ID[id or "all"]
  if not category then return end
  if RM._filter == category.id then return end
  RM._filter = category.id
  if not RM._frame then return end
  ApplyFilterAndSort()
  RelayoutList(true)
end

-- Sets the sort field, or reverses the direction when the field is already
-- selected. Picking a new field starts it in its own most-useful direction
-- rather than inheriting the previous field's.
function RM.SetSort(id, toggleDirection)
  local sort = SORT_BY_ID[id or "name"]
  if not sort then return end

  if RM._sort == sort.id and toggleDirection then
    RM._sortDesc = not RM._sortDesc
  elseif RM._sort ~= sort.id then
    RM._sort = sort.id
    RM._sortDesc = sort.desc and true or false
  end

  if not RM._frame then return end
  if RM._frame.RefreshSortControl then RM._frame.RefreshSortControl() end
  ApplyFilterAndSort()
  RelayoutList(true)
end

function RM.AddRecipient(text)
  local R = Recipients()
  if not R then
    Notice(L["RM_ERR_NOT_READY"])
    return
  end
  local key, err = R.AddManual(text)
  if not key then
    -- AddManual reports a locale KEY, not a sentence.
    Notice(L[err or "RM_ERR_NOT_READY"])
    return
  end
  -- Clear whatever is narrowing the list so the freshly added name is actually
  -- on screen. A manual add lands under "Added by you" and is favourited, so
  -- any category filter other than Favourites or All would hide it the instant
  -- it was created.
  if RM._frame and RM._frame.SearchBox then RM._frame.SearchBox:SetText("") end
  RM._filter = "all"
  RM.Refresh(true)
  ns.Print(L("RM_ADD_DONE", R.Display(key)))
end

function RM.ConfirmDelete(key, display)
  local R = Recipients()
  if not R or not key then return end
