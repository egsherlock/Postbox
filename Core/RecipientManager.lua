-- The sources still answering
--
-- An empty Guild says it fills in on its own, and now it does: the open asks
-- ContactService to re-request the sources that have not answered
-- (RefreshPending), and while any has not, the window listens for the two
-- answers -- the guild roster and the friends list -- and collects again when
-- one lands, until every source has answered or the window closes. No timer,
-- nothing polled, nothing heard while closed.
-------------------------------------------------------------
local PENDING = { "GUILD_ROSTER_UPDATE", "FRIENDLIST_UPDATE" }

local function SourcesReady()
  local CS = ns.ContactService
  if not (CS and type(CS.SourcesReady) == "function") then return true end
  local ok, ready = pcall(CS.SourcesReady)
  return (not ok) or ready and true or false
end

local function StopListening(frame)
  if not frame._listening then return end
  frame._listening = false
  for i = 1, #PENDING do frame:UnregisterEvent(PENDING[i]) end
end

local function ListenForPending(frame)
  local CS = ns.ContactService
  if CS and type(CS.RefreshPending) == "function" then pcall(CS.RefreshPending) end
  if SourcesReady() then
    StopListening(frame)
    return
  end
  if frame._listening then return end
  frame._listening = true
  for i = 1, #PENDING do frame:RegisterEvent(PENDING[i]) end
end

local function OnPendingEvent(frame)
  if not frame:IsShown() then
    StopListening(frame)
    return
  end
  local ready = SourcesReady()
  RM.Refresh()
  if ready then StopListening(frame) end
end

-------------------------------------------------------------
-- Size bounds
--
-- Measured, as the Postbox window's are, on every open: the skin has had its
-- say about fonts by then, and a host font or a translation moves all of it.
--
-- The width floor protects what does not narrow gracefully: the category
-- tiles (their captions are centred and unconstrained), the action bar at
-- rest, and the table -- a name of NAME_MIN beside Category, with the star
-- and the marks. Everything else gives way by design: the columns leave in
-- DROP's order.
--
-- A floor above the size the player chose is a LOAN (RM._loanW, RM._loanH),
-- as it is on the Postbox window: the window stands on the floor, the saved
-- size stays the player's, and the loan is handed back when the floor comes
-- down. A drag or a reset on the grip makes the size on screen the player's
-- own.
-------------------------------------------------------------

-- The width the content needs with every part at its narrowest, never under
-- MIN_W and never past MAX_W.
local function WidthFloor(frame)
  local star, caption, words = BAR_STAR_W, 0, 0
  for _, tile in ipairs(frame.CategoryTiles) do
    if tile._starTile then
      local count = tile.Count
      local shown = count:GetText()
      count:SetText(TileCountText(Theme.CountCap + 1))
      star = BAR_STAR_W + BAR_COUNT_GAP + math.ceil(Theme.TextWidth(count))
      count:SetText(shown)
    elseif tile:IsShown() then
      words = words + 1
      caption = math.max(caption, Theme.TextWidth(tile))
    end
  end
  local bar = star + BAR_GAP + words * (math.ceil(caption) + M.buttonPaddingMin + BAR_GAP)
  local need = bar + 2 * PAD + 2 * (BAND_PAD + 1)

  -- The action bar at rest, as FOOT.Layout lays it: evened to the longest
  -- caption, at the least padding.
  local buttons, longest = frame.Foot.rest, 0
  for index = 1, #buttons do
    longest = math.max(longest, Theme.TextWidth(buttons[index]))
  end
  local per = math.max(math.ceil(longest) + M.buttonPaddingMin, M.buttonMinWidth)
  need = math.max(need, #buttons * per + (#buttons - 1) * ACTION_GAP + PAD + GRIP_CLEAR + M.gap)

  -- The table: Category beside the least name, the list's insets and the
  -- scroll bar's gutter around it.
  need = math.max(need, RM.LeastRowWidth() + 2 * PAD + LIST_INSET + M.scrollGutter)

  return math.min(math.max(MIN_W, math.ceil(need)), MAX_W)
end

-- Everything above and below the rows: THE VERTICAL CHAIN, with the summary
-- line and the column names measured in the font they wear.
local function ChromeHeight(frame)
  local summary = frame.Summary
  local line = summary:GetStringHeight() or 0
  if line <= 0 then
    local _, size = summary:GetFont()
    line = tonumber(size) or 0
  end
  return math.ceil(BAND_TOP + BAND_H + SUMMARY_GAP + line + SUMMARY_GAP
                   + 2 * LIST_INSET + LAY.headH + FOOT_GAP + CTRL_H + FOOT_PAD)
end

-- The floor is MIN_ROWS whole rows; the ceiling the most whole rows at or
-- under MAX_H.
local function HeightBounds(frame)
  local chrome = ChromeHeight(frame)
  local rowH = LAY.rowH
  local rows = math.max(MIN_ROWS, math.floor((MAX_H - chrome) / rowH))
  return chrome + MIN_ROWS * rowH, chrome + rows * rowH
end

-- Sets the bounds and holds the window to them.
local function ApplyBounds(frame)
  local minW = WidthFloor(frame)
  local minH, maxH = HeightBounds(frame)
  if frame.SetResizeBounds then
    frame:SetResizeBounds(minW, minH, MAX_W, maxH)
  elseif frame.SetMinResize then
    frame:SetMinResize(minW, minH)
    frame:SetMaxResize(MAX_W, maxH)
  end

  local width, height = frame:GetWidth(), frame:GetHeight()
  local chosenW = math.min(width - (RM._loanW or 0), MAX_W)
  local chosenH = math.min(height - (RM._loanH or 0), maxH)
  local newW, newH = math.max(chosenW, minW), math.max(chosenH, minH)
  RM._loanW, RM._loanH = newW - chosenW, newH - chosenH
  if newW ~= width or newH ~= height then
    -- Pinned first, so the correction grows the window down and right rather
    -- than moving the corner the player placed.
    ns.Core.UI.Helpers.PinFrameTopLeft(frame)
    frame:SetSize(newW, newH)
  end
end

-- The default width: every column standing beside a name of DEFAULT_NAME,
-- with the list's insets and the scroll bar's gutter, as measured now.
local function DefaultWidth()
  local row = ROW.NAME_X + DEFAULT_NAME + ROW.END_W
  for c = 1, #COLS do row = row + (LAY.w[COLS[c].id] or 0) + ROW.GUTTER end
  local width = math.ceil(row + 2 * PAD + LIST_INSET + M.scrollGutter)
  return math.min(math.max(width, DEFAULT_W), DEFAULT_MAX_W)
end
RM.DefaultWidth = DefaultWidth

-- The size a first open uses: the default, or the floor where that stands
-- higher, on loan like any other. The default height is whole rows. Until
-- the player takes the grip, the size is marked as the default's (`auto` in
-- the stored size), and each open measures it again.
local function SetDefaultSize(frame)
  local minW, minH
  if frame.GetResizeBounds then minW, minH = frame:GetResizeBounds() end
  local defaultW = DefaultWidth()
  local defaultH = ChromeHeight(frame) + DEFAULT_ROWS * LAY.rowH
  local width = math.max(defaultW, tonumber(minW) or 0)
  local height = math.max(defaultH, tonumber(minH) or 0)
  RM._loanW, RM._loanH = width - defaultW, height - defaultH
  frame:SetSize(width, height)
  local store = ns.Store.EnsurePath("profile.rmWindow", {})
  if type(store) == "table" then store.auto = true end
end

