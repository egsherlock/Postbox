-- The name as the row shows it: class-coloured with a grey realm half, or,
-- for a hidden name, the plain name (the disabled token paints it). Made once
-- per entry and palette generation.
local function NameText(entry)
  local gen = Theme.SkinGeneration and Theme.SkinGeneration() or 0
  if entry._nameGen == gen and entry._nameHidden == entry.hidden and entry._nameText then
    return entry._nameText
  end
  entry._nameGen, entry._nameHidden = gen, entry.hidden
  entry._nameText = entry.hidden and entry.display or DecorateName(entry.display)
  return entry._nameText
end

-- Resolved on first render and cached on the entry. CanDelete walks the mail
-- history and every saved alt table, which is far too much to pay for several
-- hundred recipients when only a screenful is ever on show. Every path that can
-- change the answer (delete, manual add) rebuilds the entries outright.
local function ResolveDelete(entry)
  if entry.deleteChecked then return end
  entry.deleteChecked = true
  local R = Recipients()
  if not R then
    entry.canDelete, entry.deleteReason = false, "RM_ERR_LIVE_ONLY"
    return
  end
  local canDelete, reason = R.CanDelete(entry.key, entry.unlisted)
  entry.canDelete = canDelete and true or false
  entry.deleteReason = (not canDelete) and (reason or "RM_ERR_LIVE_ONLY") or nil
end

-- A text's token, set only when it changes (no repaint per bind).
local function Ink(fs, token)
  if fs._ink == token then return end
  fs._ink = token
  Theme.SetColor(fs, token)
end

-- A mark's glyph in a token, or in the accent ("accent"), kept by the
-- accent's repaints; `alpha` 1 unless given.
local function MarkTone(tex, token, alpha)
  alpha = alpha or 1
  if tex._tone ~= token then
    tex._tone = token
    if token == "accent" then
      Theme.TintAccentGlyph(tex)
    else
      Theme.ReleaseAccentGlyph(tex)
      Theme.SetColor(tex, token)
    end
  end
  if tex._alpha ~= alpha then
    tex._alpha = alpha
    tex:SetAlpha(alpha)
  end
end

-- The three marks of a row, as its entry and the pointer stand. Chrome gray
-- at rest; the accent only where it carries state (a note exists, the name
-- is hidden); the cross red under the pointer, grayed where the name cannot
-- be deleted.
local function PaintMarks(row)
  local entry = row._entry
  if not entry then return end
  local over = row._overMark
  local note, eye, cross = row.NoteMark, row.EyeMark, row.CrossMark

  if entry.note then
    MarkTone(note.Glyph, "accent")
  else
    MarkTone(note.Glyph, over == note and "textPrimary" or "textDisabled")
  end

  local art = entry.hidden and "eye-off" or "eye"
  if eye._art ~= art then
    eye._art = art
    Theme.SetGlyphArt(eye.Glyph, art)
  end
  if entry.hidden then
    MarkTone(eye.Glyph, "accent")
  else
    MarkTone(eye.Glyph, over == eye and "textPrimary" or "textSecondary")
  end

  if entry.canDelete then
    MarkTone(cross.Glyph, over == cross and "negative" or "textSecondary")
  else
    MarkTone(cross.Glyph, "textDisabled", 0.5)
  end
end

-- The star: its state, or under the pointer on a name that is not a
-- favourite, the outline in the accent -- what a click would make it.
local function PaintStar(row)
  local entry = row._entry
  if not entry then return end
  local preview = row._hover and not entry.fav
  local state = entry.fav and 1 or (preview and 2 or 0)
  if row._star == state then return end
  row._star = state
  SetStarArt(row.Fav.Icon, entry.fav and true or false)
  if preview then row.Fav.Icon:SetVertexColor(Theme.GetAccentTone("icon")) end
end

-- Selected: an accent wash and an accent edge down the left, as the Mail
-- tab's rows wear it.
local function PaintSelection(row)
  local entry = row._entry
  local on = entry ~= nil and SEL.set[entry.key] == true
  if on and not row._selBar then
    row._selWash = row:CreateTexture(nil, "BACKGROUND", nil, 1)
    row._selWash:SetAllPoints()
    row._selBar = row:CreateTexture(nil, "ARTWORK")
    row._selBar:SetWidth(2)
    row._selBar:SetPoint("TOPLEFT", row, "TOPLEFT", 0, 0)
    row._selBar:SetPoint("BOTTOMLEFT", row, "BOTTOMLEFT", 0, 0)
  end
  if row._selBar then
    if on then
      -- Re-tinted on every paint: the accent can change under a host skin.
      local r, g, b = Theme.GetAccent()
      row._selWash:SetColorTexture(r, g, b, 0.14)
      r, g, b = Theme.GetAccentTone("mark")
      row._selBar:SetColorTexture(r, g, b, 0.9)
    end
    row._selWash:SetShown(on)
    row._selBar:SetShown(on)
  end
end

-- The row's wash while the pointer is anywhere on it, its own marks and star
-- included (Character Groups' rule): each part lights the row on enter and
-- lets it go on leave, and the part entered next lights it again.
local function RowHover(row, on)
  row._hover = on and true or false
  Theme.StyleMailRow(row, row._pos, row._hover)
