    end
    GameTooltip:Show()
  end)
  row.Delete:SetScript("OnLeave", function() GameTooltip:Hide() end)

  row.Note:SetScript("OnClick", function()
    local entry = row._entry
    if entry then RM.EditNote(entry.key, entry.display, entry.note) end
  end)
  row.Note:SetScript("OnEnter", function(self)
    local entry = row._entry
    GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
