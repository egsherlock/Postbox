-- Category filters
--
-- The Send tab has the same bar under its recipient field, so the two windows
-- read as one product: the same categories in the same order, Favourites as a
-- star tile on the left, All on the right. Hidden is the one addition -- with
-- several hundred recipients, a name you hid last month is otherwise
-- unreachable.
--
-- EVERY CATEGORY IS NOW EXACT. It used to be best-effort: ContactService
-- de-duplicated across buckets, so a guildmate you had mailed came back in
-- `recent` and never in `guild`, and Guild listed the half of your guild you
-- never write to. A name now carries membership of every source it belongs to,
-- so Guild is your guild, Friends is your friends, and the apology the tile
-- tooltip used to carry (RM_CAT_TIP_APPROX) is gone rather than translated.
--
-- Recent means MAIL HISTORY and nothing else. People you recently grouped with
-- are a different fact about a different set of people; they keep their own
-- label on the row and are reachable under All.
--
-- `match` reads only fields Collect writes onto the entry, so filtering never
-- touches the data layer and never triggers a roster scan.
--
-- `source` names the ContactService source a category is a view of, where it is
-- one. It is what lets an empty category explain itself -- "you are not in a
