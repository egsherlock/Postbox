  -- opens a menu -- Sort: a row for each field, each saying its order in the
  -- field's own words; a click chooses a field in its own most useful
  -- direction, and a click on the one chosen turns it round (RM.SetSort);
  -- then Reset, drawn selected while the order is not Name, A to Z, which a
  -- right-click puts back. Postbox's own menu (Dropdown.Menu): no MenuUtil,
  -- see COMBAT_TAINT.md.
  local sortPicks = {}
  for _, sort in ipairs(SORTS) do sortPicks["sort:" .. sort.id] = sort.id end

  local sortMenu
  local memory = ns.MailMemory
  local sortButton
  local function SortMenu()
    if sortMenu then return sortMenu end
    local items = { { heading = true, name = L["SF_SORT_HEAD"] } }
    for _, sort in ipairs(SORTS) do
      items[#items + 1] = { id = "sort:" .. sort.id, name = L[sort.nameKey], flip = L[sort.nameKey] }
    end
    items[#items + 1] = { id = "reset", name = L["SF_RESET"], rule = true, action = true, glyph = "reset" }
    sortMenu = memory.SortMenu(sortButton, items, function(id)
      return sortPicks[id] ~= nil and (RM._sort or "name") == sortPicks[id]
    end, function(id)
      return id == "reset" and RM.SortIsDefault()
    end, function(id)
      if id == "reset" then
        RM.ResetSort()
      elseif sortPicks[id] then
        RM.SetSort(sortPicks[id], true)
      end
    end, function(id)
      local field = SORT_BY_ID[sortPicks[id] or ""]
      return field ~= nil and (RM._sort or "name") == field.id
        and (RM._sortDesc and true or false) ~= (field.desc and true or false)
    end, true, function() return not RM._sortDesc end)
    return sortMenu
  end

