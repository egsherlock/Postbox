local _, ns = ...

-- =====================================================================
-- Postbox :: recipient manager window
-- ---------------------------------------------------------------------
-- Curation UI on top of Core/Recipients.lua. Postbox offers a recipient
-- for every character the game hands it -- guild, friends, recent allies,
-- Blizzard's account autocomplete, plus its own saved alts and mail
-- history. On an account with a decade of alts that list is mostly noise,
-- and this window is where it gets trimmed.
--
-- Three things shape the whole file:
--
-- 1. The state map is SPARSE (see Recipients.lua): only recipients with
--    non-default state have a stored row. So the list is the UNION of the
--    live sources and the stored rows, never just the stored table.
--
-- 2. The list can be several hundred rows on a big guild. Rows are pooled
--    AND virtualised: only the rows that fit the viewport are ever created,
--    and scrolling re-fills them. WoW cannot free a frame, so a "one frame
--    per recipient" list is a permanent cost paid by everyone with a large
--    guild.
--
-- 3. A row is one line in columns -- the star, the name, Category, Class,
--    Level, Played, Mailed, then three marks (note, eye, delete) -- and
--    every width is measured from the fonts in use. A keystroke, a scroll
--    tick and a row bind make nothing: the list is sorted once per collect
--    or sort change, the filter keeps that order in a reused table, and
--    every string a row shows is made once per collect and kept on the
--    entry (the decorated name once per palette generation).
--
-- Deleting is deliberately not offered for everything. A guild member or
-- autocomplete hit is regenerated by the next scan, so "delete" would be a
-- lie; Recipients.CanDelete says which is which and the cross explains
-- itself when it is grayed.
-- =====================================================================

