-- Empties an array in place.
local function Wipe(t)
  for i = #t, 1, -1 do t[i] = nil end
  return t
end

-- Guarded like the rest of the addon guards Blizzard globals: a missing time()
-- degrades to "no relative timestamp" rather than erroring in a refresh.
local function Now()
  if type(time) ~= "function" then return nil end
  local ok, value = pcall(time)
  if ok and type(value) == "number" then return value end
  return nil
end

-- How long ago, in the one short form the window's dates take: "today",
-- then "1d", "12d", "35d" -- History's own plain age (CollectTab's
-- HistoryAgeText), each string made once and kept there. nil for no date.
local function AgeText(stamp, now)
  if type(stamp) ~= "number" or stamp <= 0 or not now then return nil end
  local days = math.floor(math.max(0, now - stamp) / 86400)
  if days <= 0 then return L["RM_LAST_TODAY"] end
  local CT = ns.CollectTab
  if CT and type(CT.HistoryAgeText) == "function" then return CT.HistoryAgeText(days, 3, "plain") end
  return L("HISTORY_AGE_D", days)
end

-- Whether a source is on in the options. A ContactService without the
-- switch answers "on".
local function SourceOn(bucket)
  local CS = ns.ContactService
  if not (CS and type(CS.SourceOn) == "function") then return true end
  local ok, on = pcall(CS.SourceOn, bucket)
  if not ok then return true end
  return on ~= false
end

-- `name` identifies the character (full address, realm half included); `text`,
-- when given, is what gets wrapped in the colour code; `ground`, where it is
-- read when not on the list ("tooltip"). See
-- ContactService.GetClassColoredName.
local function ClassColored(name, text, ground)
  local CS = ns.ContactService
  if CS and type(CS.GetClassColoredName) == "function" then
    local ok, colored = pcall(CS.GetClassColoredName, name, text, ground)
    if ok and type(colored) == "string" and colored ~= "" then return colored end
  end
  return text or name
end

-- "Bob-Draenor" -> class-coloured "Bob" plus a grey realm half, so the realm
-- never competes with the name for attention. The class is looked up by the
-- WHOLE display string: ContactService keys its cache on (name, realm).
local function DecorateName(display, ground)
  local text = tostring(display or "")
  -- A Forever name is the full name, with no realm half to dim.
  if ns.Helpers.TwoPartNames() then return ClassColored(text, nil, ground) end
  local short, realm = text:match("^([^%-]+)%-(.+)$")
  if short then
    return ClassColored(text, short, ground) .. Theme.Colorize("textSecondary", "-" .. realm, ground)
  end
  return ClassColored(text, nil, ground)
end

-- The character's class, in the player's language, or nil when nothing has
-- learned a class for this name.
local function ClassName(display)
  local text = tostring(display or "")
  if text == "" or type(LOCALIZED_CLASS_NAMES_MALE) ~= "table" then return nil end
  local CS = ns.ContactService
  if not (CS and type(CS.ClassOf) == "function") then return nil end
  local token = CS.ClassOf(text)
  return token and LOCALIZED_CLASS_NAMES_MALE[token] or nil
end

-- Whether a level and a last-played time can EVER be known for this recipient:
-- only for the player's own characters, recorded when one logs in.
local function TracksActivity(entry)
  return entry.cats.alts == true or entry.level ~= nil or entry.lastSeen ~= nil
end

-- Whether to flag "no current source offers this name any more". Display only.
-- Hidden and manual entries are excluded: a hidden recipient is still
-- perfectly real, and a manual add for another realm would be permanently
-- "stale" by construction.
local function StaleFor(entry)
  return (RM._sourcesComplete and not entry.live
          and not entry.hidden and not entry.manual) and true or false
end

-- Every dialog here is shown from this window, which is FULLSCREEN_DIALOG
-- strata, a step above where a popup opens: each show is lifted over it
-- (Theme.LiftPopup), or it would open behind the window that asked.
local function Notice(message)
  local text = tostring(message or "")
  if type(StaticPopup_Show) == "function" and type(StaticPopupDialogs) == "table" then
    if not StaticPopupDialogs[NOTICE_POPUP] then
      StaticPopupDialogs[NOTICE_POPUP] = {
        text = "%s",
        button1 = L["POPUP_OK"],
        timeout = 0,
        whileDead = true,
        hideOnEscape = true,
      }
    end
    Theme.LiftPopup(StaticPopup_Show(NOTICE_POPUP, text))
    return
  end
  ns.Print(text)
end

-- StaticPopup's edit box has moved around between clients; try every shape
-- before giving up rather than erroring inside a dialog handler.
local function PopupEditBox(dialog)
  if type(dialog) ~= "table" then return nil end
  if dialog.editBox then return dialog.editBox end
  if type(dialog.GetEditBox) == "function" then
    local ok, box = pcall(dialog.GetEditBox, dialog)
    if ok and box then return box end
  end
  local name = dialog.GetName and dialog:GetName()
  if name then return _G[name .. "EditBox"] end
  return nil
end

