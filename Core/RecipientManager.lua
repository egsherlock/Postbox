  for _, button in ipairs({ foot.add, foot.fav, foot.hide, foot.delete }) do
    button:SetScript("OnEnter", OverflowTip)
    button:SetScript("OnLeave", HideTip)
  end
  -- The tooltip names the set the button would act on, because "all listed"
  -- is only meaningful once you know what is currently listed.
  for _, button in ipairs({ foot.hideAll, foot.showAll }) do
    button:SetScript("OnEnter", BulkTip)
    button:SetScript("OnLeave", HideTip)
  end

  foot.fav:Hide()
  foot.hide:Hide()
  foot.delete:Hide()
  foot._selecting = false
  FOOT.Layout(frame)
  -- HookScript: the window persistence layer installs its own size handler and
  -- replacing it would stop the saved size being written.
  frame:HookScript("OnSizeChanged", function() FOOT.Layout(frame) end)
end

-- The list: a card, the column names along its top, the rows under them.
function BUILD.List(frame)
  local listArea = CreateFrame("Frame", nil, frame, "BackdropTemplate")
  listArea:SetPoint("TOPLEFT", frame.Summary, "BOTTOMLEFT", -2, -SUMMARY_GAP)
  listArea:SetPoint("RIGHT", frame, "RIGHT", -PAD, 0)
  listArea:SetPoint("BOTTOM", frame.Foot.add, "TOP", 0, FOOT_GAP)
  Theme.ApplyList(listArea)
  frame.ListArea = listArea

  -- UIPanelScrollFrameTemplate specifically: both skins special-case its
  -- classic slider scroll bar. The rows run to the card's edge while nothing
  -- scrolls, and stop short of the bar only while it is there (Mail Memory's
  -- rule; Theme's slim bar calls __pbGutter).
  local gutter = M.scrollGutter
  local scroll = CreateFrame("ScrollFrame", nil, listArea, "UIPanelScrollFrameTemplate")
  frame.ListScroll = scroll

  -- The column names: the cells' font, in the disabled tone.
  -- Anchored to the card, never to the scroll frame (which hangs from it):
  -- its cells stand at the x the layout gives from the left.
  local head = CreateFrame("Frame", nil, listArea)
  head:SetPoint("TOPLEFT", listArea, "TOPLEFT", LIST_INSET, -LIST_INSET)
  head:SetPoint("TOPRIGHT", listArea, "TOPRIGHT", -LIST_INSET, -LIST_INSET)
  head:SetHeight(LAY.headH)
  head.Name = Theme.CreateText(head, "secondary")
  head.Name:SetJustifyH("LEFT")
  head.Name:SetWordWrap(false)
  head.Name:SetText(L["RM_COL_NAME"])
  Theme.SetColor(head.Name, "textDisabled")
  frame.HeadCells = {}
  for c = 1, #COLS do
    local col = COLS[c]
    local fs = Theme.CreateText(head, "secondary")
    fs:SetJustifyH(col.right and "RIGHT" or "LEFT")
    fs:SetWordWrap(false)
    fs:SetText(L[col.key])
    Theme.SetColor(fs, "textDisabled")
    frame.HeadCells[col.id] = fs
  end
  frame.Head = head

  -- Two probes, never shown: the cells' font and the name's, measured.
  frame.Probe = Theme.CreateText(head, "secondary")
  frame.Probe:Hide()
  frame.NameProbe = Theme.CreateText(head, "bodySmall")
  frame.NameProbe:Hide()

  scroll:SetPoint("TOPLEFT", head, "BOTTOMLEFT", 0, 0)
  scroll:SetPoint("BOTTOMRIGHT", listArea, "BOTTOMRIGHT", -LIST_INSET, LIST_INSET)
  scroll.scrollBarHideable = 1
  scroll.__pbGutter = function(scrolling)
    scroll:SetPoint("BOTTOMRIGHT", listArea, "BOTTOMRIGHT", -(scrolling and gutter or LIST_INSET), LIST_INSET)
  end
  Theme.SlimScrollBar(scroll, listArea, LIST_INSET)

  local child = CreateFrame("Frame", nil, scroll)
  child:SetSize(math.max(scroll:GetWidth() or 0, 100), 1)
  scroll:SetScrollChild(child)
  frame.ListChild = child

  -- HookScript, not SetScript: the template installs its own handlers here and
  -- replacing them desynchronises the scroll bar.
  scroll:HookScript("OnSizeChanged", function(self, width, height)
    if width and width > 10 then child:SetWidth(width) end
    -- A taller view at the foot of the list leaves the offset past where the
    -- list now scrolls to: held to the list's end first.
    local most = math.max(0, (child:GetHeight() or 0) - (height or self:GetHeight() or 0))
    if (self:GetVerticalScroll() or 0) > most then self:SetVerticalScroll(most) end
    if RM.Layout(width or self:GetWidth()) then PlaceHeader(frame) end
    UpdateVisibleRows()
  end)
  scroll:HookScript("OnVerticalScroll", function() UpdateVisibleRows() end)

  frame.Empty = Theme.CreateText(listArea, "secondary")
  frame.Empty:SetPoint("TOPLEFT", listArea, "TOPLEFT", 24, -40)
  frame.Empty:SetPoint("BOTTOMRIGHT", listArea, "BOTTOMRIGHT", -24, 24)
  frame.Empty:SetJustifyH("LEFT")
  frame.Empty:SetJustifyV("TOP")
  frame.Empty:SetWordWrap(true)
  frame.Empty:Hide()
end

-- Position / size persistence, and the resize grip: the Postbox window's
-- helper, so the same art in the same corner under every look, the same two
-- gestures and the same hint.
function BUILD.Grip(frame)
  local store = ns.Store.EnsurePath("profile.rmWindow", {})
  local helpers = ns.Core.UI.Helpers

  local pressW, pressH, pressLoanW, pressLoanH, pressAuto

  -- The grip takes hold: the size on screen becomes the player's own.
  local function OnGripStart(f)
    pressW, pressH = f:GetWidth(), f:GetHeight()
    pressLoanW, pressLoanH = RM._loanW, RM._loanH
    RM._loanW, RM._loanH = 0, 0
    pressAuto = store.auto
    store.auto = nil
  end

  -- Released. A press that left an axis where it was has not resized it.
  local function OnGripStop(f)
    if pressW then
      local sameW = math.abs(f:GetWidth() - pressW) < 0.5
      local sameH = math.abs(f:GetHeight() - pressH) < 0.5
      if sameW then RM._loanW = pressLoanW end
      if sameH then RM._loanH = pressLoanH end
      -- A press that moved nothing leaves the default the default's.
      if sameW and sameH then store.auto = pressAuto end
      pressW = nil
    end
    UpdateVisibleRows()
  end

  -- Right-click: the size a first open uses, where the window stands.
  local function OnGripReset(f)
    helpers.PinFrameTopLeft(f)
    SetDefaultSize(f)
  end

  frame.ResizeButton = helpers.CreateResizeButton(frame, OnGripStop, OnGripStart, nil, OnGripReset)
  local grip = frame.ResizeButton
  if grip then
    local hint = { L["GRIP_TIP_DRAG"], L["GRIP_TIP_RESET"] }
    grip:HookScript("OnEnter", function(self) Theme.ShowHint(self, hint) end)
    grip:HookScript("OnLeave", function() Theme.HideHint() end)
    grip:HookScript("OnMouseDown", function() Theme.HideHint() end)
  end

  -- After the frame's own OnDragStop is set: ApplyWindowPersistence wraps it.
  -- What it writes is the window less the floor's loan.
  helpers.ApplyWindowPersistence(frame, store, {
    minW = MIN_W, maxW = MAX_W, minH = MIN_ROWS * ROW.MIN_H, maxH = MAX_H,
    extraWidthFn = function() return RM._loanW end,
    extraHeightFn = function() return RM._loanH end,
    savePlace = false,
  })
end

local function Build()
  if RM._frame then return RM._frame end

  RM._rows = RM._rows or {}
  RM._sorted = RM._sorted or {}
  RM._filtered = RM._filtered or {}
  RM._catCounts = RM._catCounts or {}
  RM._sort = RM._sort or "name"
  if RM._sortDesc == nil then
    RM._sortDesc = (SORT_BY_ID[RM._sort] and SORT_BY_ID[RM._sort].desc) and true or false
  end
  RM._filter = RM._filter or "all"
  RM._query = RM._query or ""
  RM._queryLower = RM._queryLower or ""
  -- Nothing is on loan until the first open measures the floor.
  RM._loanW, RM._loanH = 0, 0

  -- The global name is required: Helpers.RegisterEscClose puts frame:GetName()
  -- into UISpecialFrames and silently does nothing for an anonymous frame.
  local frame = CreateFrame("Frame", "PostboxRecipientManagerFrame", UIParent,
                            "BasicFrameTemplateWithInset")
  frame:SetSize(DEFAULT_W, 480)
  frame:SetPoint("CENTER", UIParent, "CENTER", 0, 0)
  frame:SetFrameStrata("FULLSCREEN_DIALOG")
  frame:SetToplevel(true)
  frame:SetClampedToScreen(true)
  frame:EnableMouse(true)
  frame:SetMovable(true)
  frame:SetResizable(true)
  frame:RegisterForDrag("LeftButton")
  frame:SetScript("OnDragStart", frame.StartMoving)
  frame:SetScript("OnDragStop", frame.StopMovingOrSizing)
  frame:SetScript("OnMouseDown", function(self) self:Raise() end)
  frame:SetScript("OnEvent", OnPendingEvent)
  -- Closed: nothing selected, nothing heard.
  frame:HookScript("OnHide", function(self)
    ClearSelection()
    StopListening(self)
  end)
  frame:Hide()

  -- Deliberately no __pbEuiAlwaysOpaque: this is a content window and follows
  -- the user's own opacity.
  if frame.TitleText then frame.TitleText:SetText(L["RM_TITLE"]) end
  Theme.ApplyFrameTheme(frame)
  ns.Core.UI.Helpers.RegisterEscClose(frame)

  BUILD.Band(frame)
  BUILD.Summary(frame)
  BUILD.Foot(frame)
  BUILD.List(frame)
  BUILD.Grip(frame)

  RM._frame = frame

  -- ApplyWindow only exists in the EllesmereUI skin; without the Apply fallback
  -- ElvUI users would get an unskinned window.
  if ns.Skin then (ns.Skin.ApplyWindow or ns.Skin.Apply)(frame) end
  -- Its glyph before its title, once the look has placed the title.
  if Theme.TitleGlyph then Theme.TitleGlyph(frame, "recipients") end

  return frame
end

