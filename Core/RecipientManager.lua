  local R = Recipients()
  if not R then return end
  for _, entry in ipairs(RM._entries or {}) do
    local hidden, fav = R.IsHidden(entry.key), R.IsFavorite(entry.key)
    if hidden ~= entry.hidden then entry._nameGen = nil end
