-- Where the window opens: right of what opened it (`anchor`, the window
-- the button stands in, and `from`, its key: "main" the Send tab's, in the
-- Postbox window wherever that stands; "options" the options panel's), or
-- the screen's middle from anywhere else (/postbox recipients), on every
-- open: a drag lasts while it stays open (Helpers.PlaceBeside). The size is
-- the player's, kept as it always was.
RM._opener, RM._from = nil, "center"

function RM.Show(anchor, from)
  local frame = Build()
  local opening = not frame:IsShown()
  if opening then
    -- Never leave the sort list and the Send tab's contact picker open at once.
    if ns.Core.UI.Dropdown and ns.Core.UI.Dropdown.CloseAll then
      ns.Core.UI.Dropdown.CloseAll()
    end
    if anchor and from and anchor.IsVisible and anchor:IsVisible() then
      RM._opener, RM._from = anchor, from
    else
      RM._opener, RM._from = nil, "center"
    end
    frame:Show()
    -- The sources still answering are asked again, and heard while open.
    ListenForPending(frame)
  end
  RM.Refresh()
  frame:Raise()
  if ns.Skin and ns.Skin.Refresh then ns.Skin.Refresh(frame) end
  -- Last: the summary line has its text and the skin its fonts, so it is
  -- measured as it will be seen.
  RM.Measure(frame)
  ApplyBounds(frame)
  -- No size stored, or the one stored is the default's own (nobody has
  -- taken the grip): the default, measured from what the list holds now.
  local saved = ns.Store.Get("profile.rmWindow")
  if not (type(saved) == "table" and tonumber(saved.height)) or (opening and saved.auto) then
    SetDefaultSize(frame)
  end
  Relayout(frame)
  if opening then
    local helpers = ns.Core.UI.Helpers
    helpers.PlaceBeside(frame, RM._opener, RM._opener and "right" or nil)
  end
end

function RM.Hide()
  if RM._frame then RM._frame:Hide() end
end

-- The face the window's text wears moved (a skin's RefitScreens, a Text
-- size): the rows' and the column names' heights and every column's width
-- measured again, and the window held to the bounds they make.
function RM.RefitText()
  local frame = RM._frame
  if not frame then return end
  RM.Measure(frame)
  if not frame:IsShown() then return end
  ApplyBounds(frame)
  RelayoutList(false)
end

-- The palette, the Mode or the look changed (Theme.RepaintAccentIcons, as
-- the Mail tab's top row hears it): the divider between the search and the
-- sort, and the rows on screen, whose names carry their colours in their
-- strings (made again for the new generation) and whose selection wears the
-- accent.
function RM.RepaintLook()
  local frame = RM._frame
  if frame and frame.Search and frame.Search.PaintJoin then frame.Search.PaintJoin() end
  local rows = RM._rows or {}
  for i = 1, #rows do rows[i]._star = nil end
  if frame and frame:IsShown() then UpdateVisibleRows() end
end

function RM.IsShown()
  return RM._frame ~= nil and RM._frame:IsShown()
end

-- Options > Reset to defaults (MailboxUI.ResetSettings) has cleared the
-- stored size and place; this puts a window already built back where a first
-- open would, or its next hide writes the old ones straight back.
function RM.ResetWindow()
  local frame = RM._frame
  if not frame then return end
  frame:ClearAllPoints()
  SetDefaultSize(frame)
  frame:SetPoint("CENTER", UIParent, "CENTER", 0, 0)
  ns.Core.UI.Helpers.PinFrameTopLeft(frame)
end

function RM.Toggle(anchor, from)
  local frame = Build()
  if frame:IsShown() then
    frame:Hide()
    return
  end
  RM.Show(anchor, from)
end
