local function Recipients() return ns.Recipients end

local function Lower(text)
  if ns.Helpers and ns.Helpers.Lower then return ns.Helpers.Lower(text) end
  return string.lower(tostring(text or ""))
end

local function Trim(text)
  if ns.Helpers and ns.Helpers.NormalizeText then return ns.Helpers.NormalizeText(text) end
  return (tostring(text or ""):gsub("^%s*(.-)%s*$", "%1"))
end

-- Guarded like the rest of the addon guards Blizzard globals: a missing time()
-- degrades to "no relative timestamp" rather than erroring in a refresh.
local function Now()
  if type(time) ~= "function" then return nil end
  local ok, value = pcall(time)
  if ok and type(value) == "number" then return value end
  return nil
end

local function FormatLastSeen(stamp)
  local now = Now()
  if type(stamp) ~= "number" or stamp <= 0 or not now then return nil end
  local diff = now - stamp
  if diff < 0 then diff = 0 end
  local days = math.floor(diff / 86400)
  if days <= 0 then return L["RM_LAST_TODAY"] end
  if days == 1 then return L["RM_LAST_YESTERDAY"] end
  if days < 60 then return L("RM_LAST_DAYS", days) end
  if days < 365 then return L("RM_LAST_MONTHS", math.floor(days / 30)) end
  return L("RM_LAST_YEARS", math.floor(days / 365))
end

-- `name` identifies the character (full address, realm half included); `text`,
-- when given, is what gets wrapped in the colour code. See
-- ContactService.GetClassColoredName.
local function ClassColored(name, text)
  local CS = ns.ContactService
  if CS and type(CS.GetClassColoredName) == "function" then
    local ok, colored = pcall(CS.GetClassColoredName, name, text)
    if ok and type(colored) == "string" and colored ~= "" then return colored end
  end
  return text or name
end

-- "Bob-Draenor" -> class-coloured "Bob" plus a grey realm half, so the realm
-- never competes with the name for attention.
--
-- The class is looked up by the WHOLE display string, not by the short half:
-- ContactService keys its cache on (name, realm), so looking up "Bob" alone
-- would ask about Bob on the player's own realm and colour a different person's
-- class onto this row.
local function DecorateName(display)
  local text = tostring(display or "")
  local short, realm = text:match("^([^%-]+)%-(.+)$")
  if short then
    return ClassColored(text, short) .. Theme.Colorize("textSecondary", "-" .. realm)
  end
  return ClassColored(text)
end

-- The character's class, in the player's language.
--
-- The class-coloured name only conveys a class to someone who knows the twelve
-- colours by sight, so the meta line spells it out. ContactService keeps its
-- class-token cache private and exposes only GetClassColoredName, so the class
-- is recovered from the colour code that function wraps the name in. The
-- reverse map is built from the client's own class colours using the same
-- formatting the colour code uses, which makes a hit an exact match rather
-- than a nearest-colour guess -- and a miss simply means no class is shown.
local classByColor

local function ClassColorKey(r, g, b)
  if type(r) ~= "number" or type(g) ~= "number" or type(b) ~= "number" then return nil end
  return string.format("%02x%02x%02x", r * 255, g * 255, b * 255)
end

local function ClassColorMap()
  if classByColor then return classByColor end
  classByColor = {}

  if type(LOCALIZED_CLASS_NAMES_MALE) ~= "table" then return classByColor end

  for token, localized in pairs(LOCALIZED_CLASS_NAMES_MALE) do
    local r, g, b
    if C_ClassColor and type(C_ClassColor.GetClassColor) == "function" then
      local ok, color = pcall(C_ClassColor.GetClassColor, token)
      if ok and type(color) == "table" then r, g, b = color.r, color.g, color.b end
    end
    if not r and type(RAID_CLASS_COLORS) == "table" and type(RAID_CLASS_COLORS[token]) == "table" then
      local color = RAID_CLASS_COLORS[token]
      r, g, b = color.r, color.g, color.b
    end
    local key = ClassColorKey(r, g, b)
    if key then classByColor[key] = localized end
  end

  return classByColor
end

-- nil when nothing has cached a class for this name -- an offline guild member
-- the roster has not returned yet, or a bare mail correspondent.
local function ClassName(display)
  local text = tostring(display or "")
  local short = text:match("^([^%-]+)")
  if not short or short == "" then return nil end
  -- Identified by the full display string, coloured as the short half, for the
  -- same reason as DecorateName: the cache is keyed on (name, realm).
  local colored = ClassColored(text, short)
  if colored == short then return nil end
  -- "|caarrggbb": skip the two alpha digits, keep the six colour ones.
  local key = colored:match("^|c%x%x(%x%x%x%x%x%x)")
  if not key then return nil end
  return ClassColorMap()[string.lower(key)]
end

-- Whether a level and a last-played time can EVER be known for this recipient.
--
-- They come from PostboxDB.altMeta, written when one of the player's own
-- characters logs in. No API reads an offline character's level, so for a guild
-- member, a friend or a mail correspondent the answer is not "not recorded
-- yet", it is "never" -- and printing "no data" on three hundred guild rows is
-- a placeholder that can never resolve. Only the player's own characters get
-- the note, because only there does the absence mean something and end.
local function TracksActivity(entry)
  return entry.cats.alts == true or entry.level ~= nil or entry.lastSeen ~= nil
end

-- Whether to flag "no current source offers this name any more". Display only,
-- never an action.
--
-- ONE definition, because four places need the answer -- the collect pass, the
-- post-bulk resync, the favourite toggle and the Hide tick -- and four readings
-- of the same rule is how the row under the cursor ends up contradicting the
-- row beside it. Hidden and manual entries are excluded: a hidden recipient is
-- still perfectly real, and a manual add for another realm would be
-- permanently "stale" by construction.
local function StaleFor(entry)
  return (RM._sourcesComplete and not entry.live
          and not entry.hidden and not entry.manual) and true or false
end

-- No `preferredIndex` on any dialog in this file, deliberately. It was a taint
-- mitigation that asked StaticPopup for the last dialog frame; 12.x's rewritten
-- StaticPopup does not read the field and no longer defines
-- STATICPOPUP_NUMDIALOGS, so every one of them was writing nil. See
-- Core/CollectTab.lua's fuller note.
local function Notice(message)
  local text = tostring(message or "")
  if type(StaticPopup_Show) == "function" and type(StaticPopupDialogs) == "table" then
    if not StaticPopupDialogs[NOTICE_POPUP] then
      StaticPopupDialogs[NOTICE_POPUP] = {
        text = "%s",
        button1 = L["POPUP_OK"],
        timeout = 0,
        whileDead = true,
        hideOnEscape = true,
      }
    end
    StaticPopup_Show(NOTICE_POPUP, text)
    return
  end
  ns.Print(text)
end

-- StaticPopup's edit box has moved around between clients; try every shape
-- before giving up rather than erroring inside a dialog handler.
local function PopupEditBox(dialog)
  if type(dialog) ~= "table" then return nil end
  if dialog.editBox then return dialog.editBox end
  if type(dialog.GetEditBox) == "function" then
    local ok, box = pcall(dialog.GetEditBox, dialog)
    if ok and box then return box end
  end
  local name = dialog.GetName and dialog:GetName()
  if name then return _G[name .. "EditBox"] end
  return nil
end

local function ToggleSound(on)
  if type(PlaySound) ~= "function" or type(SOUNDKIT) ~= "table" then return end
  local kit = on and SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_ON
                 or SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_OFF
  if kit then pcall(PlaySound, kit) end
end

-------------------------------------------------------------
-- Artwork
--
-- Atlases are preferred over texture paths where one exists: they are cut from
-- the modern high-resolution sheets and stay crisp at the sizes this window
-- uses, where the legacy standalone .blp files visibly soften.
--
-- They are also PROBED, never assumed. SetAtlas with an unknown name does not
-- error -- it clears the texture and leaves an empty square, which would be a
-- silent, client-version-dependent hole in the UI. C_Texture.GetAtlasInfo
-- settles it up front, and anything unresolved falls back to a texture path
-- that has shipped since vanilla.
-------------------------------------------------------------
local function AtlasExists(name)
  if type(name) ~= "string" or name == "" then return false end
  local getter = (C_Texture and C_Texture.GetAtlasInfo) or GetAtlasInfo
  if type(getter) ~= "function" then return false end
  local ok, info = pcall(getter, name)
  return ok and info ~= nil
end

-- The favourite star.
--
-- The old artwork was `Interface\Common\FavoritesIcon` at 18px with the off
-- state expressed as "the same star, desaturated and faint" -- two states that
-- differ only in intensity, which is exactly what is hard to read at a glance
-- in a list of several hundred rows.
--
-- The auction house's favourite pair is used instead when the client has it:
-- a filled gold star for on and a hollow outline for off. The states then
-- differ in SHAPE first and colour second, which survives both a dim host UI
-- and a colour-blind eye.
--
-- Neither state is ever faded. "Not a favourite" and "no favourites yet" are
-- both perfectly ordinary states of a working control, and a greyed-out icon
-- cannot be told apart from a disabled one, a half-loaded one, or a bug.
local STAR_ATLAS = { on = "auctionhouse-icon-favorite", off = "auctionhouse-icon-favorite-off" }
local STAR_TEXTURE = "Interface\\Common\\FavoritesIcon"
-- One token, read by this window and by Core/SendTab.lua's picker. Both files
-- used to carry the triple literally, each with a comment naming the other.
local STAR_EMPTY_TINT = ns.Core.UI.Theme.IconTints.starEmpty

local starAtlas, starProbed

local function StarAtlas()
  if not starProbed then
    starProbed = true
    -- Both or neither: an atlas star paired with a legacy outline would be two
    -- unrelated shapes sitting in the same column.
    if AtlasExists(STAR_ATLAS.on) and AtlasExists(STAR_ATLAS.off) then
      starAtlas = STAR_ATLAS
    end
  end
  return starAtlas
end

-- `on` true draws the filled gold star, false the hollow outline. Used for the
-- per-row toggle and for the Favourites tile alike, which is why there is no
-- third "dimmed" state: the tile with nothing in it shows the same outline star
-- a row that is not a favourite shows, at the same full opacity.
local function SetStarArt(texture, on)
  if not texture then return end
  local filled = on and true or false
  local atlas = StarAtlas()

  texture:SetDesaturated(false)
  texture:SetAlpha(1)

  if atlas then
    texture:SetAtlas(filled and atlas.on or atlas.off, false)
    if filled then
      texture:SetVertexColor(1, 1, 1, 1)
    else
      -- A cool near-white outline: unmistakably "not set" without reading as
      -- another shade of gold.
      texture:SetVertexColor(STAR_EMPTY_TINT[1], STAR_EMPTY_TINT[2], STAR_EMPTY_TINT[3], 1)
    end
    return
  end

  texture:SetTexture(STAR_TEXTURE)
  if filled then
    texture:SetVertexColor(1, 1, 1, 1)
  else
    -- No outline variant in the legacy asset, so the off state falls back to a
    -- colourless star -- still at full opacity, so it reads as a star that is
    -- not set rather than a star that failed to draw.
    texture:SetDesaturated(true)
    texture:SetVertexColor(STAR_EMPTY_TINT[1], STAR_EMPTY_TINT[2], STAR_EMPTY_TINT[3], 1)
  end
end

-- The sort direction arrow. Blizzard's own sortable column headers use
-- `UI-SortArrow` flipped vertically for the opposite direction; that is the
-- fallback, with the atlas pairs tried first.
local ARROW_ATLASES = {
  { up = "auctionhouse-ui-sortarrow-up", down = "auctionhouse-ui-sortarrow-down" },
  { up = "uitools-icon-chevron-up",      down = "uitools-icon-chevron-down" },
}
local ARROW_TEXTURE = "Interface\\Buttons\\UI-SortArrow"

local arrowAtlas, arrowProbed

local function ArrowAtlas()
  if not arrowProbed then
    arrowProbed = true
    for _, pair in ipairs(ARROW_ATLASES) do
      if AtlasExists(pair.up) and AtlasExists(pair.down) then
        arrowAtlas = pair
        break
      end
    end
  end
  return arrowAtlas
end

local function SetArrowArt(texture, up)
  if not texture then return end
  local atlas = ArrowAtlas()
  if atlas then
    texture:SetTexCoord(0, 1, 0, 1)
    texture:SetAtlas(up and atlas.up or atlas.down, false)
    return
  end
  texture:SetTexture(ARROW_TEXTURE)
  -- The asset's arrow occupies the left 0.5625 of the sheet and points up in
  -- its natural orientation; the down arrow is the same crop mirrored in Y.
  if up then
    texture:SetTexCoord(0, 0.5625, 0, 1)
  else
    texture:SetTexCoord(0, 0.5625, 1, 0)
  end
end

