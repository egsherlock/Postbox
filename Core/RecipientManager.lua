end

-- The groups of the player's own a character is in, joined; nil for none.
local GROUP_BUF = {}
local function GroupsOf(entry)
  local CG = ns.CharacterGroups
  if not (entry.cats.alts and CG and type(CG.List) == "function" and type(CG.HasMember) == "function") then
    return nil
  end
  Wipe(GROUP_BUF)
  local list = CG.List()
  for i = 1, #list do
    local group = list[i]
    if CG.HasMember(group.id, entry.key) then GROUP_BUF[#GROUP_BUF + 1] = CG.DisplayName(group) end
  end
  if #GROUP_BUF == 0 then return nil end
  return table.concat(GROUP_BUF, ", ")
end

