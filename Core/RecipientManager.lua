local TileCountText = Theme.CountBadgeText

-- Sizes the star tile around its count. The width is derived from the rendered
-- string, so the bar's own layout pass has to run again afterwards.
local function SetTileCount(tile, count)
  if not tile or not tile.Count then return end
  local text = TileCountText(count)
  if text then
    tile.Count:SetText(text)
    tile.Count:Show()
    tile:SetWidth(BAR_STAR_W + BAR_COUNT_GAP + math.ceil(tile.Count:GetStringWidth() or 0))
  else
    tile.Count:Hide()
    tile:SetWidth(BAR_STAR_W)
  end
end

-- HookScript, never SetScript: the factory installs the hover repaint on
-- OnEnter/OnLeave, and replacing those is how a plate silently stops repainting
-- on hover. The hooks run after it, which is what the empty-caption re-tint
-- needs.
local function CreateTile(parent, variant)
  local tile = Theme.CreatePlate(parent, variant)

  tile:HookScript("OnEnter", function(self)
    TintEmptyCaption(self)
    if self._onEnter then self._onEnter(self) end
  end)
  tile:HookScript("OnLeave", function(self)
    TintEmptyCaption(self)
    GameTooltip:Hide()
  end)

  StyleTile(tile)
  return tile
end

-------------------------------------------------------------
-- Data collection
--
-- Returns entries, total, hiddenCount, favouriteCount.
--
-- Every entry is:
--   key, display, search, sortName, category, rank, cats,
--   live, hidden, fav, manual, note, level, lastSeen, faction, stale,
--   unlisted, mailed
-- and, unless `countOnly`, the strings its row shows, made here once:
--   className, levelText, playedText, mailedText
-------------------------------------------------------------

-- Reused across collects (bounded by what the sources hold).
local COLLECT = {
  off = {},          -- bucket -> true while the options have it off
  suppressed = {},   -- key -> true: a name only an off source offers
  recentKeys = {},   -- key -> true, read only while Recent is off
  mailed = {},       -- key -> when it was last mailed (MailMemory.LastMailedInto)
  mailedMemo = {},   -- a Sent record's recipient -> its key
  MEMO_MAX = 4000,
}

local function Collect(countOnly)
  local R = Recipients()
  local entries, byKey = {}, {}
  if not R then return entries, 0, 0, 0 end

  local CS = ns.ContactService

  local buckets
  if CS and type(CS.BuildSuggestions) == "function" then
    local ok, result = pcall(CS.BuildSuggestions, "", BUILD_OPTS)
    if ok and type(result) == "table" then buckets = result end
  end
  buckets = buckets or {}

  -- STALE DETECTION SAFETY GATE. The guild roster and the friends list load
  -- asynchronously and return an empty list on a cold call, so "not
  -- returned" means "gone" only once every source that COULD hold the name
  -- has answered. ContactService decides that, per source.
  local sourcesComplete = true
  if CS and type(CS.SourcesReady) == "function" then
    local ok, ready = pcall(CS.SourcesReady)
    sourcesComplete = ok and ready and true or false
  end
  -- Set before the entry pass rather than after it: StaleFor reads it.
  RM._sourcesComplete = sourcesComplete

  local off, suppressed = COLLECT.off, COLLECT.suppressed
  for i = 1, #SWITCHED do off[SWITCHED[i]] = not SourceOn(SWITCHED[i]) end
  -- People recently grouped with have a switch of their own but no tile.
  off.grouped = not SourceOn("grouped")
  for key in pairs(suppressed) do suppressed[key] = nil end
  -- "No list offers this name" can be said only where every list could be
  -- read. ContactService hands out a switched-off source's names when asked
  -- (includeOff); one that did not would leave the guild's and the friends'
  -- names unknown with their source off, and then nothing is said.
  RM._unlistedKnown = sourcesComplete
    and (not (off.guild or off.friends) or (CS ~= nil and CS.INCLUDE_OFF == true))

  local function Entry(key)
    local entry = byKey[key]
    if not entry then
      entry = { key = key, cats = {}, rank = RANK_SAVED }
      byKey[key] = entry
      entries[#entries + 1] = entry
    end
    return entry
  end

  for rank, bucket in ipairs(BUCKETS) do
    local list = buckets[bucket]
    if type(list) == "table" then
      local isOff = off[bucket]
      for _, name in ipairs(list) do
        if type(name) == "string" and name ~= "" then
          local key = R.Key(name)
          if key ~= "" then
            if isOff then
              suppressed[key] = true
            else
              local entry = Entry(key)
              entry.live = true
              entry.cats[bucket] = true
              -- Buckets already hold addresses in the source's own spelling,
              -- so this is a valid To: value as it stands.
              entry.liveName = entry.liveName or name
              if rank < entry.rank then
                entry.rank = rank
                entry.category = L[BUCKET_LABEL[bucket]]
              end
            end
          end
        end
      end
    end
  end

  -- Recent's names, read from the record itself while Recent is off: the
  -- collect then knows them even where ContactService left the list out.
  local recentKeys = COLLECT.recentKeys
  for key in pairs(recentKeys) do recentKeys[key] = nil end
  if off.recent then
    -- Where ContactService's Recent source reads it (the profile).
    local db = type(ns.EnsureDB) == "function" and ns.EnsureDB() or nil
    local history = type(db) == "table" and db.recipientHistory or nil
    if type(history) == "table" then
      for i = 1, #history do
        if type(history[i]) == "string" then
          local key = R.Key(history[i])
          if key ~= "" then recentKeys[key] = true end
        end
      end
    end
  end

  -- The curation overlay. Rows exist only for recipients that carry non-default
  -- state, so this ADDS the ones no live source returned (hidden alts from a
  -- realm you no longer play, manual additions, notes) and annotates the rest.
  -- A name only a switched-off source offers stays out, its row kept.
  R.ForEach(function(key, row)
    local entry = byKey[key]
    if not entry then
      if suppressed[key] or recentKeys[key] or (off.alts and R.IsStoredAlt(key)) then return end
      entry = Entry(key)
    end
    entry.hidden = row.hidden == true
    entry.fav    = row.fav == true
    entry.manual = row.manual == true
    entry.note   = (type(row.note) == "string" and row.note ~= "") and row.note or nil
  end)

  -- When each was last mailed, once per collect, into the reused table.
  local mailed = COLLECT.mailed
  for key in pairs(mailed) do mailed[key] = nil end
  if not countOnly then
    local MM = ns.MailMemory
    if MM and type(MM.LastMailedInto) == "function" then
      local memo = COLLECT.mailedMemo
      local n = 0
      for _ in pairs(memo) do n = n + 1 end
      if n > COLLECT.MEMO_MAX then
        for s in pairs(memo) do memo[s] = nil end
      end
      pcall(MM.LastMailedInto, mailed, R.Key, memo)
    end
  end

  local now = Now()
  local hidden, favourites = 0, 0
  for _, entry in ipairs(entries) do
    if not entry.live then
      if entry.manual then
        entry.rank, entry.category = RANK_MANUAL, L["RM_CAT_MANUAL"]
      else
        entry.rank, entry.category = RANK_SAVED, L["RM_CAT_SAVED"]
      end
    end

    -- A stored row already carries its own casing, so Display is cheap for it.
    -- Everything else uses the name the live source gave us.
    if R.Get(entry.key) or not entry.liveName then
      entry.display = R.Display(entry.key)
    else
      entry.display = entry.liveName
    end
    if entry.display == "" then entry.display = entry.key end
    entry.search = Lower(entry.display)
    entry.sortName = entry.search

    local meta = R.AltMeta(entry.key)
    if type(meta) == "table" then
      entry.level    = tonumber(meta.level)
      entry.lastSeen = tonumber(meta.lastSeen)
      entry.faction  = (type(meta.faction) == "string" and meta.faction ~= "") and meta.faction or nil
    end

    entry.stale = StaleFor(entry)
    -- No list offers it, every list having answered: only its stored row is
    -- left of it, and Delete may take that (Recipients.CanDelete).
    entry.unlisted = (RM._unlistedKnown and not entry.live) and true or false
    entry.mailed = mailed[entry.key]

    if not countOnly then
      entry.className = ClassName(entry.display)
      entry.levelText = entry.level and tostring(entry.level) or nil
      entry.playedText = AgeText(entry.lastSeen, now)
      entry.mailedText = AgeText(entry.mailed, now)
    end

    if entry.hidden then hidden = hidden + 1 end
    if entry.fav then favourites = favourites + 1 end
  end

  return entries, #entries, hidden, favourites
end

-------------------------------------------------------------
-- Filtering and sorting
--
-- Sorted once per collect or sort change, into RM._sorted; the filter walks
-- that order into RM._filtered. Both tables are reused, and the comparators
-- are made once here: a keystroke builds no table, no closure and no sort.
-------------------------------------------------------------
local function ByName(a, b)
  if a.sortName == b.sortName then return a.key < b.key end
  return a.sortName < b.sortName
end

local function ByNameDesc(a, b)
  if a.sortName == b.sortName then return a.key > b.key end
  return a.sortName > b.sortName
end

-- The value each non-name sort orders by. An unknown is the lowest, so it
-- leads an ascending list and ends a descending one.
local SORT_VALUE = {
  category = function(entry) return entry.rank end,
  level    = function(entry) return entry.level or -1 end,
  lastSeen = function(entry) return entry.lastSeen or 0 end,
  mailed   = function(entry) return entry.mailed or 0 end,
}

-- field -> { ascending, descending }. Reversing flips the PRIMARY comparison
-- only; the name tiebreak stays A-Z in both directions.
local COMPARE = { name = { ByName, ByNameDesc } }
for field, value in pairs(SORT_VALUE) do
  COMPARE[field] = {
    function(a, b)
      local av, bv = value(a), value(b)
      if av ~= bv then return av < bv end
      return ByName(a, b)
    end,
    function(a, b)
      local av, bv = value(a), value(b)
      if av ~= bv then return av > bv end
      return ByName(a, b)
    end,
  }
end

local function ActiveCategory()
  return CATEGORY_BY_ID[RM._filter or "all"] or CATEGORY_BY_ID.all
end

-- The whole list in the order in force.
local function SortEntries()
  local sorted = Wipe(RM._sorted)
  local entries = RM._entries or {}
  for i = 1, #entries do sorted[i] = entries[i] end
  local pair = COMPARE[RM._sort or "name"] or COMPARE.name
  table.sort(sorted, pair[RM._sortDesc and 2 or 1])
end

local ClearSelection

-- Category and search are one pass and both narrow: the category decides
-- which names are on the table, the search narrows within them. The list's
-- content changes under any selection, so the selection goes.
local function ApplyFilter()
  local filtered = Wipe(RM._filtered)
  local sorted = RM._sorted
  local query = RM._queryLower or ""
  local match = ActiveCategory().match
  local n = 0
  for i = 1, #sorted do
    local entry = sorted[i]
    if ((not match) or match(entry)) and (query == "" or entry.search:find(query, 1, true)) then
      n = n + 1
      filtered[n] = entry
    end
  end
  ClearSelection()
  return filtered
end

-- Per-category totals for the tile tooltips, into a reused table.
local function CountCategories()
  local counts = RM._catCounts
  local entries = RM._entries or {}

  for _, category in ipairs(CATEGORIES) do counts[category.id] = 0 end
  counts.all = #entries

  for _, entry in ipairs(entries) do
    for _, category in ipairs(CATEGORIES) do
      if category.match and category.match(entry) then
        counts[category.id] = counts[category.id] + 1
      end
    end
  end
  return counts
end

-- Re-reads hidden/fav straight from the data layer after a bulk action, and
-- lets each changed entry's row strings be made again.
