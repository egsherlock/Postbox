-- Keys in the current filtered set that the action would actually change.
-- Favourites are never bulk-hidden: SetHidden clears fav by design, and losing
-- a hand-picked favourite to a sweep is not something a bulk button should do.
local function BulkTargets(hide)
  local keys = {}
  for _, entry in ipairs(RM._filtered or {}) do
    if hide then
      if not entry.hidden and not entry.fav then keys[#keys + 1] = entry.key end
    elseif entry.hidden then
      keys[#keys + 1] = entry.key
    end
  end
  return keys
end

function RM.ApplyBulk(hide, keys)
  local R = Recipients()
  if not R or type(keys) ~= "table" then return end
  for _, key in ipairs(keys) do
    R.SetHidden(key, hide and true or false)
  end
  SyncStates()
  RM.SoftRefresh()
end

-- Always confirms, whatever the count.
--
-- The old rule -- confirm above ten, apply silently below it -- was written
-- when the only way to narrow the list was the search box. With a category bar
-- the button under the cursor means something different depending on a tile
-- clicked minutes ago, and the confirmation is the only thing that says which.
-- Naming the scope is the whole point of asking, so asking cheaply is right.
function RM.Bulk(hide)
  local keys = BulkTargets(hide)
  local scope = ScopePhrase()

  if #keys == 0 then
    Notice(L("RM_BULK_NONE", scope))
    return
  end
  if not EnsureBulkDialog() or type(StaticPopup_Show) ~= "function" then
    RM.ApplyBulk(hide, keys)
    return
  end

  -- Snapshot: the search box and the category bar are both still usable while
  -- the dialog is up, so the action must apply to the set the dialog described
  -- rather than to whatever is listed when OK is pressed.
  local msg = hide and L("RM_BULK_HIDE_CONFIRM", #keys, scope)
                    or L("RM_BULK_SHOW_CONFIRM", #keys, scope)
  StaticPopup_Show(BULK_POPUP, msg, nil, { hide = hide, keys = keys })
end

-- Total manageable recipients, for the options-panel button badge.
