-- Favourites is a star tile on the left, exactly as on the Send tab; the word
-- tiles a switched-off source leaves share the rest evenly, their edges
-- derived from the usable width so the last tile always meets the right edge.
function BUILD.CategoryBar(frame, band, searchWrap, sortButton)
  local catBar = CreateFrame("Frame", nil, band)
  catBar:SetHeight(BAR_H)
  catBar:SetPoint("TOPLEFT", searchWrap, "BOTTOMLEFT", 0, -BAND_PAD)
  catBar:SetPoint("RIGHT", sortButton, "RIGHT", 0, 0)
  frame.CategoryBar = catBar
  frame.CategoryTiles = {}

  local wordTiles, shownTiles = {}, {}

  local function LayoutCategoryBar()
    local width = catBar:GetWidth() or 0
    if width < 60 or #wordTiles == 0 then return end
    Wipe(shownTiles)
    for i = 1, #wordTiles do
      if wordTiles[i]:IsShown() then shownTiles[#shownTiles + 1] = wordTiles[i] end
    end
    local count = #shownTiles
    if count == 0 then return end
    local left = ((frame.StarTile and frame.StarTile:GetWidth()) or BAR_STAR_W) + BAR_GAP
    local usable = width - left
    for index = 1, count do
      local tile = shownTiles[index]
      local from = left + math.floor(((index - 1) * usable / count) + 0.5)
      local to = left + math.floor((index * usable / count) + 0.5)
      tile:ClearAllPoints()
      tile:SetWidth(math.max(1, to - from - BAR_GAP))
      tile:SetPoint("TOPLEFT", catBar, "TOPLEFT", from, 0)
    end
  end

  for _, category in ipairs(CATEGORIES) do
    local tile = CreateTile(catBar, "segment")
    tile._catId = category.id

    if category.star then
      tile._starTile = true
      tile:SetWidth(BAR_STAR_W)
      tile:SetPoint("TOPLEFT", catBar, "TOPLEFT", 0, 0)
      tile.Icon = tile:CreateTexture(nil, "ARTWORK")
      tile.Icon:SetSize(BAR_STAR_ICON, BAR_STAR_ICON)
      -- LEFT-anchored rather than centred, so the star does not shift sideways
      -- when a count appears next to it.
      tile.Icon:SetPoint("LEFT", tile, "LEFT", BAR_STAR_PAD, 0)
      SetStarArt(tile.Icon, false)

      tile.Count = Theme.CreateText(tile, "bodySmall")
      tile.Count:SetPoint("LEFT", tile.Icon, "RIGHT", BAR_COUNT_GAP, 0)
      tile.Count:SetJustifyH("LEFT")
      tile.Count:SetWordWrap(false)
      Theme.SetColor(tile.Count, "accent")
      tile.Count:Hide()
      frame.StarTile = tile
    else
      tile:SetText(L[category.labelKey])
      wordTiles[#wordTiles + 1] = tile
    end

    tile._onEnter = function(self)
      local count = RM._catCounts[category.id] or 0
      -- The house's (Theme section 5b): the name white, what the tile does
      -- bright, then how many it holds.
      Theme.TipBegin(self, "ANCHOR_BOTTOM")
      Theme.TipTitle(L[category.labelKey])
      Theme.TipLine(L["RM_CAT_TIP_HINT"])
      Theme.TipLine(L("RM_CAT_TIP_COUNT", count, ns.Plural("RM_SUMMARY_RECIPIENTS", #(RM._entries or {}))))
      if count == 0 and category.source then
        local reason = SourceEmptyReason(category.source)
        if reason then
          local muted = Theme.TIP_MUTED
          GameTooltip:AddLine(L[reason], muted, muted, muted, true)
        end
      end
      if category.star and count == 0 then Theme.TipLine(L["RM_CAT_TIP_FAV_EMPTY"]) end
      GameTooltip:Show()
    end
    tile:SetScript("OnClick", function(self)
      RM.SetFilter(self._catId)
      ToggleSound(true)
    end)

    frame.CategoryTiles[#frame.CategoryTiles + 1] = tile
  end

  frame.LayoutCategoryBar = LayoutCategoryBar
  catBar:SetScript("OnSizeChanged", LayoutCategoryBar)
  LayoutCategoryBar()
end

