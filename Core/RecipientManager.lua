-- The note written, and the entry that shows it told: a note moves no row
-- and no count, so the list keeps its place and its selection.
function RM.SetNote(key, text)
  local R = Recipients()
  if not R or not key then return end
  local note = R.SetNote(key, text)
  local entries = RM._entries or {}
  for i = 1, #entries do
    if entries[i].key == key then
      entries[i].note = (type(note) == "string" and note ~= "") and note or nil
      break
    end
  end
  if RM._frame then UpdateVisibleRows() end
end

-- Keys in the current filtered set that the action would actually change.
-- Favourites are never bulk-hidden: SetHidden clears fav by design, and losing
-- a hand-picked favourite to a sweep is not something a bulk button should do.
local function BulkTargets(hide, list)
  local keys = {}
  for _, entry in ipairs(list) do
    if hide then
      if not entry.hidden and not entry.fav then keys[#keys + 1] = entry.key end
    elseif entry.hidden then
      keys[#keys + 1] = entry.key
    end
  end
  return keys
end

function RM.ApplyBulk(hide, keys)
  local R = Recipients()
  if not R or type(keys) ~= "table" then return end
  for _, key in ipairs(keys) do
    R.SetHidden(key, hide and true or false)
  end
  SyncStates()
  ClearSelection()
  RM.SoftRefresh()
end

-- Every name the question named that can still be deleted, deleted; then the
-- list collected again.
function RM.ApplyBulkDelete(keys, unlisted)
  local R = Recipients()
  if not R or type(keys) ~= "table" then return end
  for _, key in ipairs(keys) do
    if R.CanDelete(key, unlisted and unlisted[key]) then R.Delete(key) end
  end
  RM.Refresh()
end

-- Always confirms, whatever the count, and names the scope: the button under
-- the cursor means something different depending on a tile clicked minutes
-- ago, and the confirmation is the only thing that says which.
local function AskBulk(hide, list, scope)
  local keys = BulkTargets(hide, list)
  if #keys == 0 then
    Notice(L("RM_BULK_NONE", scope))
    return
  end
  if not EnsureBulkDialog() or type(StaticPopup_Show) ~= "function" then
    RM.ApplyBulk(hide, keys)
    return
  end
  -- Snapshot: the search box and the category bar are both still usable while
  -- the dialog is up, so the action applies to the set the dialog described.
  local msg = hide and ns.Plural("RM_BULK_HIDE_CONFIRM", #keys, scope)
                    or ns.Plural("RM_BULK_SHOW_CONFIRM", #keys, scope)
  Theme.LiftPopup(StaticPopup_Show(BULK_POPUP, msg, nil, { hide = hide, keys = keys }))
end

-- "Hide all listed" / "Show all listed".
function RM.Bulk(hide)
  AskBulk(hide, RM._filtered, ScopePhrase())
end

-- The foot's buttons while rows are selected: "favorite", "hide" or "delete".
local SELECTED = {}
function RM.BulkSelected(kind)
  local list = SelectedEntries(SELECTED)
  local n = #list
  if n == 0 then return end
  local R = Recipients()
  if not R then return end
  local scope = ns.Plural("RM_SCOPE_SELECTED", n)

  if kind == "favorite" then
    for i = 1, n do
      if not list[i].fav then R.SetFavorite(list[i].key, true) end
    end
    SyncStates()
    ClearSelection()
    ToggleSound(true)
    RM.SoftRefresh()
    return
  end

  if kind == "hide" then
    AskBulk(true, list, scope)
    return
  end

  -- Delete: the names that can go, the rest skipped and said.
  local keys, unlisted, skipped, alts = {}, {}, 0, 0
  for i = 1, n do
    local entry = list[i]
    if R.CanDelete(entry.key, entry.unlisted) then
      keys[#keys + 1] = entry.key
      unlisted[entry.key] = entry.unlisted or nil
      if R.IsStoredAlt and R.IsStoredAlt(entry.key) then alts = alts + 1 end
    else
      skipped = skipped + 1
    end
  end
  if #keys == 0 then
    Notice(ns.Plural("RM_BULK_DELETE_NONE", n))
    return
  end
  if not EnsureBulkDeleteDialog() or type(StaticPopup_Show) ~= "function" then
    RM.ApplyBulkDelete(keys, unlisted)
    return
  end
  local msg = ns.Plural("RM_BULK_DELETE_CONFIRM", #keys, scope)
  if alts > 0 then msg = msg .. "\n\n" .. ns.Plural("RM_BULK_DELETE_ALTS", alts) end
  if skipped > 0 then msg = msg .. "\n\n" .. ns.Plural("RM_BULK_DELETE_SKIPPED", skipped) end
  Theme.LiftPopup(StaticPopup_Show(BULK_DELETE_POPUP, msg, nil, { keys = keys, unlisted = unlisted }))
end

