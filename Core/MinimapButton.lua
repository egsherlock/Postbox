local function ShowTooltip(button)
  GameTooltip:SetOwner(button, "ANCHOR_BOTTOMLEFT")

  -- Same content as the default indicator: the shared formatter when the
  -- client provides it, the same strings by hand when it does not.
  local senders = LatestSenders()
  local header = (#senders > 0 and HAVE_MAIL_FROM) or HAVE_MAIL or ""
  local formatted = type(FormatUnreadMailTooltip) == "function"
    and pcall(FormatUnreadMailTooltip, GameTooltip, header, senders)
  if not formatted then
    GameTooltip:SetText(header)
    for i = 1, #senders do
      GameTooltip:AddLine(senders[i], 1, 1, 1)
    end
  end

  GameTooltip:AddLine(L["MINIMAP_TIP_HINT"], 0.6, 0.6, 0.6, true)
  GameTooltip:Show()
end

local function OnDragUpdate(button)
  local prefs = NormalizeSettings(Settings())

  -- Detached: the icon follows the cursor itself, in minimap-relative
  -- coordinates so it keeps riding the map through scale and position
  -- changes. Saved live, same as the rim drag.
  if prefs.detached then
    local minimap = _G.Minimap
    local centerX, centerY = minimap:GetCenter()
    local scale = minimap:GetEffectiveScale()
    if not centerX or not scale or scale == 0 then return end
    local cursorX, cursorY = GetCursorPosition()
    prefs.offsetX = cursorX / scale - centerX
    prefs.offsetY = cursorY / scale - centerY
    Reposition(button)
    return
  end

  local angle = AngleFromCursor()
  if angle then
    prefs.position = "CUSTOM"
    prefs.angle = angle
    Reposition(button)
  end
end

local function Build()
  if MB._button then return MB._button end
  local minimap = _G.Minimap
  if not minimap then return nil end

  -- Unnamed: see the header comment before naming this frame.
  local button = CreateFrame("Button", nil, minimap)
  button:Hide()
  button:RegisterForClicks("LeftButtonUp", "RightButtonUp")
  button:RegisterForDrag("LeftButton")
  -- A detached icon is placed by hand and must never be lost off-screen; on
  -- the rim the clamp simply never engages.
  button:SetClampedToScreen(true)

  local shadow = button:CreateTexture(nil, "BACKGROUND", nil, -1)
  shadow:SetPoint("CENTER", button, "CENTER", 0, -1)
  shadow:SetTexture(MEDIA .. "minimap-glow.tga")
  shadow:SetVertexColor(0, 0, 0)
  shadow:SetAlpha(0.9)
  shadow:Hide()
  button.shadow = shadow

  local glow = button:CreateTexture(nil, "BACKGROUND", nil, 0)
  glow:SetPoint("CENTER")
  glow:SetTexture(MEDIA .. "minimap-glow.tga")
  glow:SetBlendMode("ADD")
  glow:Hide()
  button.glow = glow

  local icon = button:CreateTexture(nil, "ARTWORK")
  icon:SetPoint("CENTER")
  button.icon = icon

  -- Hover feedback reuses the glow art faintly, so the hit target reads as a
  -- control without adding chrome.
  button:SetHighlightTexture(MEDIA .. "minimap-glow.tga", "ADD")
  local highlight = button:GetHighlightTexture()
  highlight:ClearAllPoints()
  highlight:SetPoint("CENTER")
  highlight:SetSize(DEFAULTS.size * GLOW_SCALE, DEFAULTS.size * GLOW_SCALE)
  highlight:SetAlpha(0.35)
  button.highlight = highlight

  -- A slow breathe on the glow while mail waits. BOUNCE alternates the fade
  -- direction each loop, so there is no snap at the ends.
  local pulse = glow:CreateAnimationGroup()
  pulse:SetLooping("BOUNCE")
  local fade = pulse:CreateAnimation("Alpha")
  fade:SetFromAlpha(1)
  fade:SetToAlpha(0.55)
  fade:SetDuration(1.6)
  fade:SetSmoothing("IN_OUT")
  button.pulse = pulse

  button:SetScript("OnEnter", ShowTooltip)
  button:SetScript("OnLeave", function() GameTooltip:Hide() end)
  button:SetScript("OnClick", function(self, mouseButton)
    if IsShiftKeyDown() then return end -- shift is the drag modifier
    if mouseButton == "RightButton" then
      -- Settings live behind the deliberate click; a stray left-click must
      -- never fling a window at the player.
      local Panel = ns.OptionsPanel
      if Panel and type(Panel.Toggle) == "function" then
        Panel.Toggle(self)
      end
      return
    end
    -- Left is the mail action: what the mailbox held when this character
    -- last saw it. Toggle itself declines while a real mailbox is open.
    local Memory = ns.MailMemory
    if Memory and type(Memory.Toggle) == "function" then
      Memory.Toggle(self)
    end
  end)

  -- Shift-drag anywhere on the rim; a plain drag is ignored so a click can
  -- never smear the position, and a locked icon ignores even shift. The
  -- angle is saved live, so releasing the button anywhere leaves the icon
  -- exactly where it looks.
  button:SetScript("OnDragStart", function(self)
    if not IsShiftKeyDown() then return end
    if Settings().lock then return end
    self:SetScript("OnUpdate", OnDragUpdate)
  end)
  button:SetScript("OnDragStop", function(self)
    self:SetScript("OnUpdate", nil)
    -- A drag can silently turn a corner preset into CUSTOM; if the options
    -- panel is open on screen, its controls should say so without needing
    -- to be closed and reopened.
    local Panel = ns.OptionsPanel
    if Panel and type(Panel.RefreshControls) == "function" then
      Panel.RefreshControls()
    end
  end)

  MB._button = button
  return button
end

-------------------------------------------------------------
-- 7. State
--
-- Off means OFF. While the setting is disabled this module's session
-- footprint is nothing at all: no frames, no event registrations, no touch
-- on the default indicator. The runtime below is brought up on enable and
-- torn back down on disable, so the only trace an enable-then-disable can
-- leave is the two hooks WoW provides no way to remove -- both of which are
-- guarded to dead code while inactive.
-------------------------------------------------------------

local Refresh -- forward: the event handlers below re-enter it

local function OnMailEvent()
  Refresh()
end

-- Re-derives everything on zone-in: both host UIs rebuild and resize the
-- minimap at login and on profile switches, which moves the rim. A loading
-- screen is also when a host rebuilds its buttons, so an exhausted finder
-- gets its tries back rather than staying in fallback forever.
local function OnEnterWorld()
  euiSkin.fallback = false
  euiSkin.tries = 0
  Refresh()
end

local runtimeActive = false

local function SetRuntimeActive(on)
  on = on == true
  if runtimeActive == on then return end
  runtimeActive = on

  if on then
    ns.Events.Register("UPDATE_PENDING_MAIL", OnMailEvent)
    ns.Events.Register("PLAYER_ENTERING_WORLD", OnEnterWorld)
    local minimap = _G.Minimap
    if minimap and not MB._sizeHooked then
      MB._sizeHooked = true
      hooksecurefunc(minimap, "SetSize", function()
        if runtimeActive and MB._button and MB._button:IsShown() then
          Reposition(MB._button)
        end
      end)
    end
    return
  end

  ns.Events.Unregister("UPDATE_PENDING_MAIL", OnMailEvent)
  ns.Events.Unregister("PLAYER_ENTERING_WORLD", OnEnterWorld)
end

Refresh = function()
  local prefs = Settings()

  if prefs.enabled ~= true or NotificationsRuledOut() then
    SetRuntimeActive(false)
    SetDefaultSuppressed(false)
    RestoreEuiSkin()
    euiSkin.tries = 0
    euiSkin.fallback = false
    if MB._button then MB._button:Hide() end
    return
  end

  SetRuntimeActive(true)

  -- One invariant while enabled: the default indicator is silenced, in BOTH
  -- modes. Skin mode once left the Blizzard frame alive so EllesmereUI's
  -- Show/Hide hooks on it could drive their icon -- but those hooks answer
  -- every mail event with a full relayout that resets their mouseover-hidden
  -- button row to full alpha and re-hides it on a deferred timer, a visible
  -- flash per AH purchase. Constant suppression generates zero Show/Hide
  -- traffic; the visibility sync those hooks performed is done below.
  SetDefaultSuppressed(true)

  -- EllesmereUI's minimap module running: restyle its icon in place, leave
  -- position and size to them.
  if EuiSkinCandidate() and not euiSkin.fallback then
    if MB._button then MB._button:Hide() end
    if ApplyEuiSkin() then
      euiSkin.tries = 0
      SyncEuiButtonShown()
      return
    end
    -- Their button is built a beat after login (and can lag a settings
    -- change); wait for it a few times before concluding their internals
    -- have changed shape and falling back to Postbox's own button. The
    -- latch matters: without it every later Refresh would re-enter this
    -- block and churn state around each mail event.
    if euiSkin.tries < EUI_SKIN_MAX_TRIES then
      euiSkin.tries = euiSkin.tries + 1
      if not euiSkin.timerArmed then
        euiSkin.timerArmed = true
        C_Timer.After(2, function()
          euiSkin.timerArmed = false
          Refresh()
        end)
      end
      return
    end
    euiSkin.fallback = true
  end

  RestoreEuiSkin()
  local button = Build()
  if not button then return end
  ApplyLook(button)

  -- Update the highlight to the configured size too; it is anchored art, not
  -- a child, so ApplyLook's SetSize does not reach it.
  local size = tonumber(prefs.size) or DEFAULTS.size
  button.highlight:SetSize(size * GLOW_SCALE, size * GLOW_SCALE)

  button:SetShown(MailWaiting())
end

MB.Refresh = Refresh

-- One line for /postbox debug. This exists because a transient "no icon"
-- report is undiagnosable after the fact: the fields below are everything
-- visibility depends on, captured at the moment the report is built.
function MB.Diagnose()
  return string.format(
    "runtime %s | suppressing %s | eui candidate %s applied %s tries %d fallback %s | own button %s | mail waiting %s",
    tostring(runtimeActive), tostring(suppressing),
    tostring((EuiSkinCandidate())), tostring(euiSkin.applied),
    euiSkin.tries, tostring(euiSkin.fallback),
    (MB._button and MB._button:IsShown()) and "shown" or "hidden/none",
    tostring((MailWaiting())))
end

-- Called by Skin_EllesmereUI.RefreshAccents so an accent retune repaints a
-- visible icon immediately rather than on the next mail event.
function MB.RefreshLook()
  if euiSkin.applied then
    ApplyEuiSkin()
    return
  end
  local button = MB._button
  if button and button:IsShown() then ApplyLook(button) end
end

