-- The legacy MiniMapMailFrame global no longer exists on 12.x; the frame is
-- reachable only by this path.
local function DefaultIndicator()
  local cluster = _G.MinimapCluster
  local holder = cluster and cluster.IndicatorFrame
  return holder and holder.MailFrame or nil
end

-- A plain Hide() does not stick: UPDATE_PENDING_MAIL re-Shows the frame on
-- login, on new mail, and on every pending-mail re-sync. So suppression
-- takes the event away from the frame instead, which stops it EVER Showing.
--
-- Why not a Show hook that re-hides? That was the first implementation, and
-- it flickered EllesmereUI: EUI hooks both Show and Hide on this frame and
-- answers each with a full relayout of every minimap indicator and button
-- row, so hide-after-show cost two relayouts per mail event and visibly
-- blinked its mouseover-hidden elements. With the event unregistered the
-- frame stays silent and EUI is never poked at all -- which also keeps EUI's
-- own mail icon (driven by those same hooks) from popping up alongside ours
-- mid-session.
local suppressing = false

local function SetDefaultSuppressed(on)
  on = on == true
  if suppressing == on then return end
  local mail = DefaultIndicator()
  if not mail then return end
  suppressing = on

  if on then
    mail:UnregisterEvent("UPDATE_PENDING_MAIL")
    -- Hide() on an already-hidden frame fires nothing, so this pokes EUI's
    -- relayout hook at most once, at the moment the user flips the option.
    mail:Hide()
    return
  end

  -- Hand the event back, then run Blizzard's own handler once to resync --
  -- not Show(): the envelope texture inside the frame is only made visible
  -- after a notification flipbook completes, so a bare Show() would restore
  -- an empty frame. The handler re-derives everything from HasNewMail().
  mail:RegisterEvent("UPDATE_PENDING_MAIL")
  local handler = mail:GetScript("OnEvent")
  if handler then pcall(handler, mail, "UPDATE_PENDING_MAIL") end
end

-------------------------------------------------------------
-- 3. EllesmereUI skin mode
--
-- When EllesmereUI's minimap module is running, ITS mail icon is the mail
-- icon: it cannot be switched off in its options and it is resurfaced by
-- many of its layout passes. Fighting that is a losing game. So in that
-- situation Postbox does not draw a button -- it restyles EllesmereUI's
-- button in place (icon art, accent tint, glow) and leaves position and
-- size to EllesmereUI, which is what its own options already control.
--
-- The Blizzard frame IS still silenced in this mode (see Refresh): its
-- Show/Hide traffic is what EllesmereUI's relayout hooks answer, and each
-- answer flashes their mouseover-hidden button row for a beat. Starving the
-- event starves their event-driven visibility sync too, so Postbox performs
-- that sync itself -- SetShown(HasNewMail()), the same call their own code
-- makes -- while their layout passes keep agreeing from HasNewMail() direct.
--
-- The button is found by its `_indicatorKey == "_mail"` field. Everything
-- changed is snapshotted first and restored exactly on disable, and if a
-- future EllesmereUI stops exposing this shape the skin quietly never
-- applies and Postbox falls back to its own button.
-------------------------------------------------------------

local EUI_SKIN_MAX_TRIES = 8

-- `fallback` latches when the finder exhausts its tries while the module is
-- still a candidate: without the latch, every Refresh would re-enter the
-- candidate block and flip the default indicator's suppression off and on
-- around each mail event. Cleared on disable and on PLAYER_ENTERING_WORLD.
local euiSkin = { button = nil, saved = nil, applied = false,
                  tries = 0, timerArmed = false, fallback = false }

local function EuiMinimapProfile()
  local host = _G.EllesmereUI
  if not (host and host.Lite and type(host.Lite.GetAddon) == "function") then
    return nil
  end
  local ok, mm = pcall(function()
    local sub = host.Lite.GetAddon("EllesmereUIMinimap", true)
    return sub and sub.db and sub.db.profile and sub.db.profile.minimap
  end)
  if ok and type(mm) == "table" then return mm end
  return nil
end

-- Skin mode is a candidate whenever the module is loaded and its profile
-- does not say disabled. An unreadable profile counts as enabled: the module
-- ships enabled by default, and guessing "disabled" would flash Postbox's
-- own button at login before the profile arrives.
local function EuiSkinCandidate()
  if not (C_AddOns and type(C_AddOns.IsAddOnLoaded) == "function") then
    return false
  end
  if not C_AddOns.IsAddOnLoaded("EllesmereUIMinimap") then return false end
  local mm = EuiMinimapProfile()
  return not mm or mm.enabled ~= false
end

local RestoreEuiSkin -- forward: the finder restores an orphaned button on rebuild

local function FindEuiMailButton()
  local minimap = _G.Minimap
  local cached = euiSkin.button
  if cached and cached:GetParent() == minimap then return cached end

  if not minimap then return nil end
  local kids = { minimap:GetChildren() }
  for i = 1, #kids do
    local child = kids[i]
    if child and child ~= MB._button and child._indicatorKey == "_mail" then
      if euiSkin.button and euiSkin.button ~= child then
        -- EllesmereUI rebuilt its button mid-session. Restore the orphan
        -- verbatim -- it would otherwise keep our texture and its stood-down
        -- hover fields forever -- and drop the snapshot, which described the
        -- old frame, not this one.
        RestoreEuiSkin()
        euiSkin.saved = nil
      end
      euiSkin.button = child
      return child
    end
  end
end

local function ApplyEuiSkin()
  local btn = FindEuiMailButton()
  local icon = btn and btn._icon
  if not icon then return false end

  if not euiSkin.saved then
    local w, h = icon:GetSize()
    -- The atlas fields alone cannot restore a button whose _upAtlas was nil,
    -- so the icon's actual art is snapshotted alongside them.
    euiSkin.saved = { up = btn._upAtlas, over = btn._overAtlas, w = w, h = h,
                      atlas = icon:GetAtlas(), texture = icon:GetTexture() }
  end

  local prefs = Settings()
  local spec = ICONS[prefs.icon] or ICONS[DEFAULTS.icon]
  local r, g, b = 1, 1, 1
  if prefs.accent ~= false then r, g, b = ns.Theme.GetAccent() end

  if prefs.icon == "blizzard" then
    -- "Blizzard" here means EllesmereUI's stock look, which is the same art.
    local saved = euiSkin.saved
    btn._upAtlas, btn._overAtlas = saved.up, saved.over
    if saved.up then icon:SetAtlas(saved.up)
    elseif saved.atlas then icon:SetAtlas(saved.atlas)
    elseif saved.texture then icon:SetTexture(saved.texture) end
    icon:SetSize(euiSkin.saved.w, euiSkin.saved.h)
    icon:SetVertexColor(1, 1, 1)
  else
    -- Their OnEnter/OnLeave/OnMouseDown swap the icon atlas from these two
    -- fields; nil means those scripts stand down, which is exactly what a
    -- replaced texture needs. Restored verbatim on disable.
    btn._upAtlas, btn._overAtlas = nil, nil
    if spec.atlas then
      icon:SetAtlas(spec.atlas)
    else
      icon:SetTexture(spec.texture)
    end
    local side = math.max(10, math.min(btn:GetWidth(), btn:GetHeight()) - 6)
    icon:SetSize(side, side * (spec.aspect or 1))
    if spec.tintable then
      icon:SetVertexColor(r, g, b)
    else
      icon:SetVertexColor(1, 1, 1)
    end
  end

  local shadow = btn.__pbMailShadow
  if prefs.shadow == true then
    if not shadow then
      shadow = btn:CreateTexture(nil, "BACKGROUND", nil, -1)
      shadow:SetPoint("CENTER", icon, "CENTER", 0, -1)
      shadow:SetTexture(MEDIA .. "minimap-glow.tga")
      shadow:SetVertexColor(0, 0, 0)
      shadow:SetAlpha(0.9)
      btn.__pbMailShadow = shadow
    end
    shadow:SetSize(btn:GetWidth() * 1.3, btn:GetHeight() * 1.3)
    shadow:Show()
  elseif shadow then
    shadow:Hide()
  end

  local glow = btn.__pbMailGlow
  if prefs.glow == true then
    if not glow then
      glow = btn:CreateTexture(nil, "BACKGROUND")
      glow:SetPoint("CENTER", icon, "CENTER")
      glow:SetTexture(MEDIA .. "minimap-glow.tga")
      glow:SetBlendMode("ADD")
      btn.__pbMailGlow = glow
      local pulse = glow:CreateAnimationGroup()
      pulse:SetLooping("BOUNCE")
      local fade = pulse:CreateAnimation("Alpha")
      fade:SetFromAlpha(1)
      fade:SetToAlpha(0.55)
      fade:SetDuration(1.6)
      fade:SetSmoothing("IN_OUT")
      btn.__pbMailPulse = pulse
    end
    glow:SetSize(btn:GetWidth() * 1.6, btn:GetHeight() * 1.6)
    glow:SetVertexColor(r, g, b)
    glow:Show()
    if prefs.pulse ~= false then
      if not btn.__pbMailPulse:IsPlaying() then btn.__pbMailPulse:Play() end
    else
      btn.__pbMailPulse:Stop()
    end
  elseif glow then
    btn.__pbMailPulse:Stop()
    glow:Hide()
  end

  euiSkin.applied = true
  return true
end

RestoreEuiSkin = function()
  if not euiSkin.applied then return end
  euiSkin.applied = false

  local btn = euiSkin.button
  local saved = euiSkin.saved
  if not (btn and saved) then return end

  btn._upAtlas, btn._overAtlas = saved.up, saved.over
  local icon = btn._icon
  if icon then
    if saved.up then icon:SetAtlas(saved.up)
    elseif saved.atlas then icon:SetAtlas(saved.atlas)
    elseif saved.texture then icon:SetTexture(saved.texture) end
    icon:SetSize(saved.w, saved.h)
    icon:SetVertexColor(1, 1, 1)
  end
  if btn.__pbMailGlow then
    btn.__pbMailPulse:Stop()
    btn.__pbMailGlow:Hide()
  end
  if btn.__pbMailShadow then btn.__pbMailShadow:Hide() end
end

-- Skin mode starves the Blizzard frame's UPDATE_PENDING_MAIL (see Refresh),
-- which also starves the event-driven half of EllesmereUI's own visibility
-- sync -- so that half is performed here, with the exact call their sync
-- makes. Their periodic layout passes read HasNewMail() directly and agree.
local function SyncEuiButtonShown()
  local btn = euiSkin.button
  if not (btn and euiSkin.applied) then return end

  local waiting = MailWaiting()
  btn:SetShown(waiting)

  -- EllesmereUI anchors this button only inside its own layout pass, and
  -- only while the button is SHOWN -- their builder gives it no points at
  -- all. So after a login with no unread mail (their sync hid it before
  -- any layout ran) the button has no rect, and showing it here renders it
  -- nowhere. Their layout runs from their hooks on the Blizzard frame: one
  -- Show()/Hide() poke fires it -- sync, then anchor -- and their module
  -- alpha-zeroes that frame, so nothing is seen. Gated on the missing
  -- points, this fires at most once per session; anchors persist once set.
  if waiting and btn:GetNumPoints() == 0 then
    local mail = DefaultIndicator()
    if mail then
      pcall(mail.Show, mail)
      pcall(mail.Hide, mail)
    end
  end
end

-- The options panel asks this to decide which controls make sense: in skin
-- mode, position and size belong to EllesmereUI.
function MB.IsHostStyled()
  return EuiSkinCandidate() and not euiSkin.fallback
end

